#!/bin/sh
#
# Домовой — инкрементальное обновление индекса ast-index.
#
# Индекс ускоряет поиск по коду (класс, символ, использования, иерархия) и
# живёт вне репозитория, в каталоге данных пользователя. Хук держит его
# свежим: полная пересборка 93 файлов занимает ~210 мс, инкрементальная —
# ~20 мс, поэтому обновление после каждой правки дешевле, чем поиск по
# устаревшему индексу.
#
# Отсутствие ast-index ошибкой не считается. В отличие от gitleaks в
# pre-commit, индекс не рубеж защиты, а удобство: у кого инструмента нет,
# тот работает без него, и хук молча уступает дорогу. Репозиторий
# публичный, и падать на чужой машине из-за необязательного инструмента
# он не должен.
set -eu

# ------------------------------------------------------------
# Поиск ast-index
#
# Причина ровно та же, что у find_gitleaks в .githooks/pre-commit:
# winget кладёт бинарь в Links, и этот каталог не всегда попадает в PATH
# оболочки, из которой запускается хук. Проверено — в этом проекте не
# попадает.
# ------------------------------------------------------------
find_ast_index() {
    if command -v ast-index >/dev/null 2>&1; then
        command -v ast-index
        return 0
    fi

    for candidate in \
        "${LOCALAPPDATA:-}/Microsoft/WinGet/Links/ast-index.exe" \
        "${HOME:-}/AppData/Local/Microsoft/WinGet/Links/ast-index.exe" \
        "${HOME:-}/.local/bin/ast-index" \
        "${HOME:-}/.cargo/bin/ast-index" \
        "/usr/local/bin/ast-index" \
        "/opt/homebrew/bin/ast-index"
    do
        if [ -x "$candidate" ]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done

    return 1
}

AST_INDEX="$(find_ast_index)" || exit 0

# Вывод глушится намеренно: хук срабатывает после каждой правки файла, и
# три строки статистики в транскрипте на каждую правку — шум. Ошибка
# обновления тоже не повод рушить ход: индекс отстанет, поиск останется
# работоспособным, следующий запуск догонит.
"$AST_INDEX" update >/dev/null 2>&1 || exit 0

exit 0
