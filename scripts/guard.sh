# ------------------------------------------------------------------
# Проверка 7. Снимок числа тестов понижен
#
# tests/test-count.baseline — база инварианта результата: число выполненных
# случаев, с которым сверяется каждый прогон (scripts/test-count-invariant.sh).
# Понизить снимок — единственный способ провести уменьшение числа тестов так,
# чтобы инвариант остался зелёным, и это свойство диффа, а не прогона:
# поэтому проверка живёт здесь, а сам инвариант — там.
#
# МЕТКИ-ОБХОДА У ЭТОЙ ПРОВЕРКИ НЕТ, и это решение владельца, а не недоделка.
# Законное уменьшение — удаление функциональности вместе с её тестами —
# перестаёт быть операцией обычного PR и становится ручной операцией
# человека: прямым коммитом в main либо временным снятием обязательной
# проверки. Гейт обязан сказать это вслух: молчащий об отсутствии обхода
# отправляет следующего искать несуществующую метку.
#
# Переименование файла снимка проверка ловит, а не пропускает: путь здесь
# фиксированный, поэтому в ревизии PR числа по нему нет — BASELINE_HEAD пуст
# при непустом BASELINE_BASE, и срабатывает ветка «снимок числа тестов удалён».
# Второй рубеж на тот же приём — сам инвариант: без снимка по ожидаемому пути
# он краснеет с текстом «сравнить не с чем».
# ------------------------------------------------------------------
BASELINE_FILE='tests/test-count.baseline'

# Числом считается строка целиком из цифр. Только такие строки и сравниваются:
# иначе правка пояснений в шапке снимка читалась бы как «42 → 0», и гейт начал
# бы краснеть на законной работе. Шумящий гейт перестают читать.
baseline_number() {
    git show "$1:$BASELINE_FILE" 2>/dev/null | tr -d '\r' | grep -m1 -oE '^[0-9]+$'
}

BASELINE_BASE="$(baseline_number "$BASE_SHA")"
BASELINE_HEAD="$(baseline_number "$HEAD_SHA")"

if [ -z "$BASELINE_BASE" ] && [ -n "$BASELINE_HEAD" ]; then
    section 'Проверка 7: снимок числа тестов появился в этом PR'
    printf '    сравнивать не с чем: в базовой ревизии %s числа нет. Со следующего PR сравнение работает.\n' \
        "$BASELINE_FILE"
elif [ -n "$BASELINE_BASE" ] && [ -z "$BASELINE_HEAD" ]; then
    section 'Проверка 7: снимок числа тестов удалён'
    annotate "$BASELINE_FILE" '1' \
        "Снимок числа тестов удалён или перестал содержать число ($BASELINE_FILE, в базовой ревизии было $BASELINE_BASE). Без снимка инвариант числа выполненных случаев сравнивает не с чем — это не способ сделать проверку зелёной, а способ её выключить. Метки на это нет: если тесты убраны законно, снимок правит человек вручную."
elif [ -n "$BASELINE_BASE" ] && [ -n "$BASELINE_HEAD" ] \
    && [ "$BASELINE_HEAD" -lt "$BASELINE_BASE" ]; then
    section 'Проверка 7: снимок числа тестов понижен'
    annotate "$BASELINE_FILE" "$(first_changed_line "$BASELINE_FILE")" \
        "Снимок числа тестов понижен: $BASELINE_BASE в базовой ревизии против $BASELINE_HEAD в этом PR. Понижение снимка — это уменьшение числа выполненных тестов, проведённое так, чтобы инвариант остался зелёным. Метки, снимающей эту проверку, нет вовсе: если уменьшение законно, потому что удалена функциональность вместе с её тестами, снимок правит человек вручную, а не PR агента."
fi

# ------------------------------------------------------------------
# Проверка 8. Отчёт о прогоне в диффе
#
# Инвариант числа выполненных случаев (scripts/test-count-invariant.sh)
# суммирует executed по всем найденным trx-отчётам, а порог покрытия в CI —
# lines-covered и lines-valid по глобу отчётов под каталогом результатов.
# Суммирование выбрано сознательно, и поэтому оба обходятся одинаково:
# подложенный в PR отчёт добивает сумму до нужной при убывших тестах или
# упавшем покрытии. .gitignore этого не останавливает — git add -f снимает его
# строку, — и проверки 2 и 3 на таком PR молчат: опустошённый набор
# [InlineData] не убавляет атрибутов и не добавляет строк подавления.
#
# Нарушение одно, формулировки две: *.trx — отчёт о прогоне, любой файл под
# каталогом результатов ([Tt]est[Rr]esult*/ на любой глубине, то же множество,
# что в .gitignore) — сюда же отчёт покрытия. Шаблон каталога обязателен:
# *.trx в одиночку оставил бы открытым coverage.cobertura.xml.
#
# Смотрятся пути добавленные, изменённые и переименованные; удаление ранее
# закоммиченного отчёта — починка, а не нарушение. Переименование ловится и
# без -M: оно распадается на удаление и добавление, а добавление в фильтре
# есть, — поэтому сценарий переименования держит фильтр, а не -M. Шаблон каталога совпадёт и
# с каталогом вроде TestResultFormatter/ — это то же множество, что скрывает
# .gitignore, и файл туда без git add -f не попадает.
#
# МЕТКИ-ОБХОДА У ЭТОЙ ПРОВЕРКИ НЕТ, как у проверки 7: отчёт прогона в PR не
# нужен ни в одном законном случае. Гейт говорит это вслух.
# ------------------------------------------------------------------
REPORT_DIR_RE='(^|/)[Tt]est[Rr]esult[^/]*/'
REPORT_FILE_RE='\.trx$'

REPORT_CANDIDATES="$WORK/report-candidates.txt"
if ! git -c core.quotepath=false diff --name-only --diff-filter=d -M \
    "$BASE_SHA" "$HEAD_SHA" > "$REPORT_CANDIDATES"; then
    printf '::error::Не удалось получить список добавленных и изменённых файлов %s..%s.\n' \
        "$BASE_SHA" "$HEAD_SHA" >&2
    exit 2
fi

REPORT_HIT="$WORK/report.tsv"
: > "$REPORT_HIT"
while IFS= read -r file; do
    [ -n "$file" ] || continue
    if [[ "$file" =~ $REPORT_FILE_RE ]]; then
        printf 'trx\t%s\n' "$file" >> "$REPORT_HIT"
    elif [[ "$file" =~ $REPORT_DIR_RE ]]; then
        printf 'dir\t%s\n' "$file" >> "$REPORT_HIT"
    fi
done < "$REPORT_CANDIDATES"

if [ -s "$REPORT_HIT" ]; then
    section 'Проверка 8: в PR закоммичен результат прогона тестов'
    while IFS=$'\t' read -r kind file; do
        [ -n "$file" ] || continue
        if [ "$kind" = 'trx' ]; then
            annotate "$file" "$(first_changed_line "$file")" \
                "Отчёт о прогоне тестов закоммичен: $file. Отчёт не коммитится: он вход инварианта числа выполненных случаев, который суммирует executed по всем найденным trx-отчётам, и подложенный отчёт добивает сумму до снимка при убывших тестах. .gitignore от git add -f не защищает. Метки, снимающей эту проверку, нет: отчёт прогона в PR не нужен ни в одном законном случае — уберите файл из PR (git rm --cached)."
        else
            annotate "$file" "$(first_changed_line "$file")" \
                "Файл под каталогом результатов прогона закоммичен: $file. Каталог результатов — вход проверок CI: инварианта числа выполненных случаев и порога покрытия, которые читают отчёты оттуда, и подложенный файл (trx-отчёт, отчёт покрытия) подменяет результат прогона. .gitignore от git add -f не защищает. Метки, снимающей эту проверку, нет — уберите файл из PR (git rm --cached)."
        fi
    done < "$REPORT_HIT"
fi

# ------------------------------------------------------------------
# Проверка 9. Разрушительный и неидемпотентный SQL в миграции
#
# Проверка 4 ловит имена методов API EF. Миграция с сырым SQL —
# migrationBuilder.Sql("…") — законная форма, и в ней ни одно из этих имён не
# встречается. Здесь — правила приложения B.4 ТЗ советника по той же
# механике: добавленные строки файлов под src/Domovoy.Data/Migrations/.
# Отдельная проверка, а не правило внутри проверки 4: номер — публичный
# интерфейс сообщений гейта, и неидемпотентный CREATE TABLE под номером 4
# изменил бы смысл её сообщения.
#
# Пять правил, у каждого своё имя в сообщении:
#
#   DELETE FROM или TRUNCATE — данные удаляются необратимо;
#   DROP без IF EXISTS — DROP TABLE|COLUMN|INDEX|CONSTRAINT, за которым не
#     стоит IF EXISTS (у DROP INDEX — и после CONCURRENTLY);
#   ACCESS EXCLUSIVE — блокировка, останавливающая работающий экземпляр;
#   ADD CONSTRAINT … PRIMARY KEY — перестройка ключа на живой таблице;
#   CREATE TABLE или ADD COLUMN, за которым не стоит IF NOT EXISTS.
#
# IF [NOT] EXISTS снимает срабатывание только с того оператора, за ключевым
# словом которого стоит: соседний оператор на той же строке, комментарий или
# хвост C# с этими словами его не снимают. Идемпотентные ADD COLUMN IF NOT
# EXISTS и CREATE INDEX … IF NOT EXISTS корректны и нарушением не считаются. Сравнение без учёта регистра:
# шаблоны в нижнем регистре, строка приводится к нему же. Слова внутри правила
# разделены пробельным классом, поэтому имена API EF (CreateTable(,
# AddColumn<, DropTable) с правилами не совпадают. Однословное truncate
# ограничено с обеих сторон: без границ оно совпало бы с IsTruncated,
# TruncateAfter и .Truncate( в сгенерированном коде; в awk нет \b, граница —
# класс символов. Обход — метка agent/allow-destructive-migration, как у
# проверки 4: DELETE FROM в миграции переноса данных законен, и решает человек.
#
# ЧЕГО ПРОВЕРКА 9 НЕ ЛОВИТ
#
#   Разбор SQL не ведётся: проверка ищет текст в добавленных строках, та же
#   граница, что у проверки 2. Отсюда:
#   - ложная тревога на комментарии или строковом литерале, упоминающем
#     drop table или truncate; адрес — метка человека;
#   - оператор, разнесённый по строкам (DROP на одной, TABLE на следующей),
#     не ловится; IF [NOT] EXISTS, перенесённый на следующую строку, не
#     снимает срабатывание — ложная тревога, адрес тот же;
#   - DROP TABLE IF EXISTS проходит, хотя данные теряет: правило взято из
#     B.4 буквально, вызов API EF DropTable ловит проверка 4;
#   - живость таблицы не видна: ADD CONSTRAINT … PRIMARY KEY срабатывает и на
#     таблице, созданной в той же миграции;
#   - вызов API EF AddPrimaryKey здесь не ловится — его ловит проверка 4;
#     вызовы DropIndex, DropForeignKey, DropPrimaryKey, DropUniqueConstraint
#     не ловятся ни здесь, ни в проверке 4, хотя сырые DROP INDEX и DROP
#     CONSTRAINT ловит правило «DROP без IF EXISTS»: под критерий допуска
#     проверки 4 они не подходят;
#   - ведущая граница у delete, drop, access, add, create стоит ради
#     единообразия, но сценарием не проверена: проверены обе границы
#     truncate.
#
#   Харнесс проверки целиком синтетический: миграций в дереве ноль, и формы,
#   которые даст настоящий генератор EF, могут отличаться от фикстур.
#
#   Порядок версий миграций не проверяется — отложен. Посылка правила
#   («forward-only схема пропускает файл с меткой ниже текущей») для EF не
#   установлена: EF применяет пропущенные миграции, а не только новые. Предмет
#   другой — имена файлов против истории базы, а не содержимое добавленных
#   строк, — и проверять его не на чем, пока миграций нет.
# ------------------------------------------------------------------
SQL_LEAD='(^|[^a-z0-9_])'
SQL_TAIL='([^a-z0-9_]|$)'

SQL_RULE_NAMES=(
    'DELETE FROM или TRUNCATE'
    'DROP без IF EXISTS'
    'ACCESS EXCLUSIVE'
    'ADD CONSTRAINT … PRIMARY KEY'
    'CREATE TABLE или ADD COLUMN без IF NOT EXISTS'
)

# Порядок совпадает с SQL_RULE_NAMES: массивы читаются параллельно.
SQL_RULE_PATTERNS=(
    "${SQL_LEAD}delete[[:space:]]+from${SQL_TAIL}|${SQL_LEAD}truncate[[:space:]]"
    "${SQL_LEAD}drop[[:space:]]+(table|column|index|constraint)${SQL_TAIL}"
    "${SQL_LEAD}access[[:space:]]+exclusive${SQL_TAIL}"
    "${SQL_LEAD}add[[:space:]]+constraint[[:space:]].*primary[[:space:]]+key${SQL_TAIL}"
    "${SQL_LEAD}(create[[:space:]]+table|add[[:space:]]+column)${SQL_TAIL}"
)

# Идемпотентная форма правила — ключевое слово оператора и сразу за ним
# IF [NOT] EXISTS. Из строки в нижнем регистре вырезается каждое её вхождение,
# и шаблон правила проверяется на остатке. Привязка к ключевому слову, а не к
# строке: исключение, сверенное со всей строкой, снимало срабатывание и с
# соседнего оператора — «DROP TABLE a; DROP TABLE IF EXISTS b;», — и с
# оператора, за которым IF EXISTS стоит в комментарии или в хвосте C# после
# литерала. У DROP INDEX между ключевым словом и IF EXISTS допускается
# CONCURRENTLY. Пустое — идемпотентной формы у правила нет.
SQL_RULE_IDEMPOTENT=(
    ''
    "drop[[:space:]]+(table|column|index|constraint)[[:space:]]+(concurrently[[:space:]]+)?if[[:space:]]+exists"
    ''
    ''
    "(create[[:space:]]+table|add[[:space:]]+column)[[:space:]]+if[[:space:]]+not[[:space:]]+exists"
)

SQL_RULE_REASONS=(
    'удаление строк в миграции необратимо, а TRUNCATE стирает таблицу целиком'
    'удаление объекта схемы без IF EXISTS падает при повторной накатке и теряет данные'
    'блокировка ACCESS EXCLUSIVE останавливает чтение и запись работающего экземпляра на всё время миграции'
    'добавление первичного ключа на живой таблице перестраивает её под блокировкой и падает на дублях'
    'создание без IF NOT EXISTS неидемпотентно: повторная накатка падает на уже существующем объекте'
)

SQL_HIT="$WORK/sql.tsv"
: > "$SQL_HIT"
for index in "${!SQL_RULE_PATTERNS[@]}"; do
    idempotent="${SQL_RULE_IDEMPOTENT[$index]}"
    rule_re="${SQL_RULE_PATTERNS[$index]}"
    while IFS=$'\t' read -r file line text; do
        [ -n "$file" ] || continue
        if [ -n "$idempotent" ]; then
            # Каждый проход вырезает найденное вхождение и укорачивает строку,
            # поэтому цикл конечен.
            rest="${text,,}"
            while [[ "$rest" =~ $idempotent ]]; do
                rest="${rest/"${BASH_REMATCH[0]}"/ }"
            done
            if ! [[ "$rest" =~ $rule_re ]]; then
                continue
            fi
        fi
        printf '%s\t%s\t%s\t%s\n' "$file" "$line" "$index" "$text" >> "$SQL_HIT"
    done < <(select_lines '+' "${SQL_RULE_PATTERNS[$index]}" "$MIGRATION_FILE_RE" 'без регистра')
done

if [ -s "$SQL_HIT" ] && [ "$ALLOW_DESTRUCTIVE" -eq 0 ]; then
    section 'Проверка 9: разрушительный или неидемпотентный SQL в миграции'
    while IFS=$'\t' read -r file line index text; do
        [ -n "$file" ] || continue
        annotate "$file" "$line" \
            "SQL в миграции нарушает правило «${SQL_RULE_NAMES[$index]}»: $file. Причина: ${SQL_RULE_REASONS[$index]}. Схема и код деплоятся не атомарно, и миграция обязана быть совместимой с работающей версией. Нужна метка agent/allow-destructive-migration на PR — её ставит человек, убедившись, что операция нужна и безопасна. Проверка ищет текст в строке, SQL не разбирает: срабатывание на комментарии или литерале снимается той же меткой."
        quote_line "$file" "$line" "$text"
    done < "$SQL_HIT"
elif [ -s "$SQL_HIT" ]; then
    section 'Проверка 9: SQL в миграции разрешён меткой agent/allow-destructive-migration'
    while IFS=$'\t' read -r file line index text; do
        [ -n "$file" ] || continue
        printf '    разрешено: %s:%s — правило «%s»\n' "$file" "$line" "${SQL_RULE_NAMES[$index]}"
    done < "$SQL_HIT"
fi

# ------------------------------------------------------------------
# Итог
# ------------------------------------------------------------------
printf '\n'
if [ "$VIOLATIONS" -eq 0 ]; then
    printf 'Гейт целостности: нарушений нет (%s..%s).\n' \
        "${BASE_SHA:0:7}" "${HEAD_SHA:0:7}"
    exit 0
fi

printf 'Гейт целостности: нарушений — %s (%s..%s).\n' \
    "$VIOLATIONS" "${BASE_SHA:0:7}" "${HEAD_SHA:0:7}"
printf 'Гейт ловит не баги, а обход проверок. Зелёная сборка, полученная\n'
printf 'подавлением или удалением теста, хуже красной: она врёт.\n'
printf 'Метки ставит человек, а не агент: agent/allow-protected,\n'
printf 'agent/allow-contract, agent/allow-destructive-migration.\n'
exit 1
