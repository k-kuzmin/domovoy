#!/usr/bin/env bash
#
# Домовой — счётчик кругов планового ревью.
#
# ЧТО ДЕЛАЕТ
#
# Читает метки задачи со стандартного ввода — по одной в строке, ровно в том
# виде, в каком их отдаёт `gh issue view --json labels --jq '.labels[].name'`,
# — и печатает на stdout две строки:
#
#   round=<номер круга>
#   stop=<true|false>
#
# Больше на stdout не выводится ничего: шаг workflow дописывает этот вывод в
# `$GITHUB_OUTPUT` как есть, и человекочитаемая строка рядом испортила бы
# выход job. Диагностика идёт в stderr — там она попадает в лог запуска.
#
# ПОЧЕМУ ОТДЕЛЬНЫМ СКРИПТОМ
#
# Счётчик PR-половины живёт логикой внутри job `round` в agent-review.yml —
# и проверить его можно только живым прогоном. Агентский цикл выключен, и
# для плановой половины это означало бы, что потолок кругов не проверен
# ничем, кроме рассуждения. Вынесенная арифметика прогоняется харнессом
# `scripts/plan-review-round.test.sh` на наборах меток.
#
# ГРАНИЦА
#
# Скрипт не ходит в GitHub и ничего не знает о PR: счётчик кругов ревью
# диффа живёт на метках `review/1..2` PR и сюда не переносится — другой
# объект и другие метки (запись 0016 о раздельных счётчиках).
#
# КАК ЗАПУСКАТЬ
#
#   gh issue view 12 --repo owner/name --json labels --jq '.labels[].name' \
#     | bash scripts/plan-review-round.sh
#
# Код возврата: 0 — счёт выполнен, 2 — ошибка запуска.
#
set -euo pipefail

# Потолок кругов — два, запись 0016. Он общий для ревью диффа и ревью плана:
# третий круг того же ревьюера по тому же предмету — не ревью, а его
# имитация.
CEILING=2

usage() {
  cat <<'HELP'
Считает номер круга планового ревью по меткам задачи.

Метки читаются со стандартного ввода — по одной в строке. На stdout идут
ровно две строки: round=<N> и stop=<true|false>.

  gh issue view 12 --json labels --jq '.labels[].name' \
    | bash scripts/plan-review-round.sh
HELP
}

while [ $# -gt 0 ]; do
  case "$1" in
    -h | --help)
      usage
      exit 0
      ;;
    *)
      printf 'Неизвестный аргумент: %s\n' "$1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

labels="$(cat)"

# Счёт идёт от единицы: первый круг — тот, у которого меток ещё нет вовсе.
# Метка `plan-review/N` ставится ДО вызова модели, поэтому она считает круги,
# а не успехи: запуск, умерший посреди ревью, круг потратил.
round=1
for n in $(seq 1 "$CEILING"); do
  if printf '%s\n' "$labels" | grep -qxF "plan-review/$n"; then
    round=$((n + 1))
  fi
done

stop=false
if [ "$round" -gt "$CEILING" ]; then
  stop=true
fi

printf 'round=%s\n' "$round"
printf 'stop=%s\n' "$stop"
printf 'Круг планового ревью: %s, остановка: %s\n' "$round" "$stop" >&2
