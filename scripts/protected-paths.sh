#!/usr/bin/env bash
#
# БЕЗ ОБВЯЗКИ: файл не запускается, а источается — гейт целостности и валидатор
# плана берут отсюда один список защищённых путей, своего шага в CI у него нет.
#
# Домовой — защищённые пути, один список на всех потребителей.
#
# ЗАЧЕМ
#
# Одно множество путей описано в трёх местах: `.github/CODEOWNERS`, раздел
# «Файлы, которые агент не трогает» в `.claude/CLAUDE.md` и регулярные
# выражения для механической проверки. Первые два — для человека, третье — для
# машины, и расхождение между тремя CODEOWNERS называет дефектом.
#
# Потребителей у машинной формы стало два: гейт целостности смотрит на дифф
# PR, валидатор плана — на план до того, как появился хоть один коммит. Пока
# список лежал внутри `guard.sh`, у валидатора был выбор между своей копией и
# чтением CODEOWNERS с переводом glob'ов в регулярные выражения. Копия — это
# четвёртое описание того же множества, перевод glob'ов — вторая машинка с
# собственными ошибками. Поэтому список вынесен сюда, а потребители его
# источают.
#
# КАК ИСПОЛЬЗОВАТЬ
#
#   source "<каталог скриптов>/protected-paths.sh"
#   # дальше доступны PROTECTED_PATTERNS и protected_regex
#
# Источающий обязан проверить, что массив не пуст: файл не найден или пуст —
# это не «нет защищённых путей», а сломанная проверка. Молча пропускающий гейт
# хуже отсутствующего: он создаёт видимость.
#
# ЧЕГО ЗДЕСЬ НЕТ
#
# Ни одного действия: только определения. Файл источается из скриптов с
# разными режимами оболочки, и `set -e` или вывод здесь менял бы поведение
# потребителя.

# ------------------------------------------------------------------
# Список синхронизирован с .github/CODEOWNERS — он источник истины.
# Порядок и группировка повторяют CODEOWNERS, чтобы расхождение было видно
# глазами при сравнении двух файлов.
# ------------------------------------------------------------------
PROTECTED_PATTERNS=(
    # --- Конфигурация качества и сборки ---
    'Directory\.Build\.props'
    'Directory\.Packages\.props'
    '\.editorconfig'
    'global\.json'
    '(.+/)?[^/]+\.ruleset'
    # --- Сам пайплайн ---
    '\.github/.+'
    '\.githooks/.+'
    'scripts/.+'
    # Конфигурация пайплайна: таблица сигналов риск-скора и политика маршрута.
    # Пока уровень никого не маршрутизировал, файл ехал в диффе PR и был виден
    # на ревью — этого хватало. С появлением pipeline/route.json уровень
    # определяет, сколько кругов ревью пройдёт задача, и незащищённый файл
    # маршрута — это гейт, который агент снимает себе сам.
    'pipeline/.+'
    # --- Правила проекта и принятые решения ---
    '\.claude/CLAUDE\.md'
    '\.claude/agents/.+'
    'docs/rules/.+'
    'docs/decisions/.+'
    # --- Поиск секретов ---
    '\.gitleaks\.toml'
    # --- Данные ---
    'src/Domovoy\.Data/Migrations/.+'
    # --- Контракт API и генерация клиента ---
    'contracts/.+'
    'src/Domovoy\.Mobile\.Core/Generated/.+'
    # --- Платформенное и подписи ---
    'src/Domovoy\.Mobile\.App/Platforms/.+'
    'src/Domovoy\.Mobile\.App/Resources/.+'
    '(.+/)?[^/]+\.keystore'
    '(.+/)?[^/]+\.mobileprovision'
    '(.+/)?[^/]+\.p12'
    '(.+/)?google-services\.json'
    '(.+/)?GoogleService-Info\.plist'
    '(.+/)?AndroidManifest\.xml'
    '(.+/)?Info\.plist'
)

# Собирает из списка одно якорное регулярное выражение. Функция, а не
# переменная: потребитель источает файл в разный момент своей работы, а
# вычисление на месте источения привязало бы значение к этому моменту.
protected_regex() {
    local IFS='|'
    printf '^(%s)$' "${PROTECTED_PATTERNS[*]}"
}
