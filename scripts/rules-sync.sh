#!/usr/bin/env bash
#
# Домовой — сверка правил шагов работы с промптами и указателем.
#
# ЗАЧЕМ
#
# Правила шагов живут в docs/rules/, промпты .github/workflows/agent-*.yml на
# них ссылаются, а .claude/CLAUDE.md держит указатель. Три места, и разъехаться
# они могут молча: файл переименовали — промпт ссылается в пустоту и агент
# работает без правил; файл добавили — указатель о нём не знает и локальная
# сессия его не откроет.
#
# Проверка механическая именно поэтому. Ссылка, которую никто не проверял, —
# это не источник правил, а надежда на него.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Каждая ссылка на docs/rules/*.md из промптов ведёт в существующий файл.
#   2. Каждый файл правил упомянут хотя бы одним промптом (README — указатель,
#      он исключён: на него ссылаются файлы правил, а не промпты).
#   3. Промпт шага ссылается на правила своего шага: agent-triage.yml — на
#      triage.md, agent-review.yml — на review-*.md. Соответствие выводится из
#      имён файлов, а не задано списком: список был бы копией, которая тоже
#      разъезжается.
#   4. Каждый файл правил указан в .claude/CLAUDE.md.
#   5. Относительные markdown-ссылки внутри docs/rules/*.md ведут в
#      существующие файлы.
#   6. Ни один файл правил не пересказывает .claude/CLAUDE.md: совпадающая
#      формулировка длиной от десяти слов считается копией.
#
# ЧЕГО ЭТА СВЕРКА НЕ ЛОВИТ
#
# Проверки 1–5 смотрят на связи: путь существует, файл упомянут промптом.
# Содержание для них безразлично, и потому копию правила они пропускают —
# ссылка-то на месте. Проверка 6 смотрит на содержание, но и она видит
# только дословное совпадение: пересказ другими словами не ловится вовсе.
# Механически он и недостижим, а делать вид, что достижим, хуже, чем назвать
# границу. Пример прямо в репозитории: список запрещённых подавлений в
# .claude/CLAUDE.md и его пересказ в docs/rules/review-correctness.md —
# порог десяти слов его не видит, а снижать порог ради него значит получить
# ложные тревоги на всём остальном.
#
# Между этими двумя случаями есть третий, и он тоже не ловится: дословная
# копия короче окна. В репозитории таких две — их видно, если поставить
# COPY_WINDOW=9. Перечислены в #73 и лечатся заменой на отсылку, а не
# снижением порога здесь.
#
# КАК ЗАПУСКАТЬ
#
#   bash scripts/rules-sync.sh              # корень репозитория
#   bash scripts/rules-sync.sh /путь/к/копии
#
# Код возврата: 0 — сходится, 1 — есть расхождения, 2 — ошибка запуска.
#
set -uo pipefail

ROOT="${1:-}"
if [ -z "$ROOT" ]; then
    ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fi

if [ ! -d "$ROOT" ]; then
    printf 'Не найден каталог: %s\n' "$ROOT" >&2
    exit 2
fi

cd "$ROOT" || exit 2

RULES_DIR='docs/rules'
POINTER='.claude/CLAUDE.md'

if [ ! -d "$RULES_DIR" ]; then
    printf 'Не найден каталог правил: %s/%s\n' "$ROOT" "$RULES_DIR" >&2
    exit 2
fi

VIOLATIONS=0

report() {
    # Формат GitHub Actions: сообщение попадает в аннотации к файлу.
    printf '::error file=%s::%s\n' "$1" "$2"
    VIOLATIONS=$((VIOLATIONS + 1))
}

note() {
    printf '  %s\n' "$1"
}

# Промпты шагов и файлы правил. Оба списка берутся из файловой системы:
# источник истины — то, что лежит в репозитории, а не перечисление в скрипте.
prompts=()
while IFS= read -r f; do
    [ -n "$f" ] && prompts+=("$f")
done < <(find .github/workflows -maxdepth 1 -name 'agent-*.yml' 2>/dev/null | sort)

rules=()
while IFS= read -r f; do
    [ -n "$f" ] && rules+=("$f")
done < <(find "$RULES_DIR" -maxdepth 1 -name '*.md' 2>/dev/null | sort)

if [ "${#prompts[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного .github/workflows/agent-*.yml\n' >&2
    exit 2
fi

if [ "${#rules[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного файла правил в %s\n' "$RULES_DIR" >&2
    exit 2
fi

printf 'Правила: %d файл(ов), промпты: %d\n\n' "${#rules[@]}" "${#prompts[@]}"

# ------------------------------------------------------------------
# Проверка 1. Ссылки из промптов ведут в существующие файлы.
# ------------------------------------------------------------------
for prompt in "${prompts[@]}"; do
    while IFS= read -r ref; do
        [ -z "$ref" ] && continue
        if [ ! -f "$ref" ]; then
            report "$prompt" "ссылка на несуществующие правила: $ref"
        fi
    done < <(grep -ohE 'docs/rules/[A-Za-z0-9._-]+\.md' "$prompt" | sort -u)
done

# ------------------------------------------------------------------
# Проверка 2. Каждый файл правил упомянут хотя бы одним промптом.
#
# README исключён намеренно: это указатель, и ссылаются на него файлы
# правил. Промпт ревью на него ссылается, но требовать этого от всех —
# значит требовать лишнего чтения на каждом шаге.
# ------------------------------------------------------------------
for rule in "${rules[@]}"; do
    base="$(basename "$rule")"
    [ "$base" = 'README.md' ] && continue
    if ! grep -qF "$rule" "${prompts[@]}"; then
        report "$rule" "файл правил не упомянут ни одним промптом agent-*.yml"
    fi
done

# ------------------------------------------------------------------
# Проверка 3. Промпт шага ссылается на правила своего шага.
#
# Шаг берётся из имени файла: agent-<шаг>.yml. Правила шага — файл, чьё
# имя начинается с того же слова: review → review-correctness.md и
# review-security.md. Так соответствие выводится из имён, а не задано
# списком, который сам разъезжается.
# ------------------------------------------------------------------
for prompt in "${prompts[@]}"; do
    step="$(basename "$prompt" .yml)"
    step="${step#agent-}"

    expected=()
    for rule in "${rules[@]}"; do
        base="$(basename "$rule" .md)"
        if [ "$base" = "$step" ] || [ "${base#"$step"-}" != "$base" ]; then
            expected+=("$rule")
        fi
    done

    if [ "${#expected[@]}" -eq 0 ]; then
        report "$prompt" "у шага «$step» нет файла правил в $RULES_DIR"
        continue
    fi

    for rule in "${expected[@]}"; do
        if ! grep -qF "$rule" "$prompt"; then
            report "$prompt" "промпт шага «$step» не ссылается на свои правила: $rule"
        fi
    done
done

# ------------------------------------------------------------------
# Проверка 4. Каждый файл правил указан в .claude/CLAUDE.md.
#
# Указатель — единственное, что читает локальная сессия, не заходя в
# .github/**. Файл правил, которого в нём нет, для живого режима не
# существует.
# ------------------------------------------------------------------
if [ ! -f "$POINTER" ]; then
    report "$POINTER" "не найден указатель на правила"
else
    for rule in "${rules[@]}"; do
        [ "$(basename "$rule")" = 'README.md' ] && continue
        if ! grep -qF "$rule" "$POINTER"; then
            report "$POINTER" "правила не указаны в файле правил проекта: $rule"
        fi
    done
fi

# ------------------------------------------------------------------
# Проверка 5. Относительные ссылки внутри правил ведут в существующие
# файлы. Правила ссылаются на записи решений и друг на друга — битая
# ссылка здесь стоит того же, что битая ссылка из промпта.
# ------------------------------------------------------------------
for rule in "${rules[@]}"; do
    dir="$(dirname "$rule")"
    while IFS= read -r target; do
        [ -z "$target" ] && continue
        case "$target" in
            http*|'#'*) continue ;;
        esac
        # Якорь после пути к файлу отбрасывается: проверяется файл.
        target="${target%%#*}"
        [ -z "$target" ] && continue
        resolved="$dir/$target"
        # Нормализация ../ вручную: realpath есть не в каждом окружении, а
        # путей здесь единицы.
        while printf '%s' "$resolved" | grep -q '/[^/][^/]*/\.\./'; do
            resolved="$(printf '%s' "$resolved" | sed -E 's#/[^/]+/\.\./#/#')"
        done
        if [ ! -e "$resolved" ]; then
            report "$rule" "битая ссылка: $target"
        fi
    done < <(grep -ohE '\]\([^)]+\.md[^)]*\)' "$rule" \
        | sed -E 's/^\]\(//; s/\)$//' | sort -u)
done

# ------------------------------------------------------------------
# Проверка 6. Файл правил не пересказывает .claude/CLAUDE.md.
#
# docs/rules/README.md формулирует инвариант: правила шагов — слой поверх
# CLAUDE.md, а не замена ему; где правило уже записано в указателе, здесь
# стоит ссылка. Копия правила хуже отсутствующей ссылки: ссылку видно, а
# копия разъезжается молча — поправили одну сторону, и агент читает две
# разные версии одного правила, не зная об этом.
#
# Постановка обратная сверке двух копий. Сверять побайтово пришлось бы,
# разметив блоки маркерами, — а это превращает CLAUDE.md в генерируемый
# файл. Здесь копии просто запрещены: лечится замена копии на ссылку, то
# есть убирается причина, а не последствие.
#
# Совпадением считается окно в десять слов, встречающееся и в указателе, и
# в файле правил. Порог замерен на репозитории: окно из восьми слов даёт
# попадания в описании назначения каталога в README.md, а это не правило;
# окно из десяти — только настоящие копии. Порог выбран так, чтобы каждое
# попадание было тем, с которым человек согласится: первое ложное — это
# место, где заводится маркер-исключение, а исключений здесь нет.
# Совпадение целого предложения не годится: переписанная пунктуация его
# обходит, а окно — нет.
# ------------------------------------------------------------------
COPY_WINDOW=10

# Нормализация текста перед нарезкой. Из markdown остаётся проза:
#   - fenced-блоки выброшены: код не формулировка правила, а команду вроде
#     `dotnet build` файл шага законно повторяет — в implement.md стоят те
#     же четыре команды, что в разделе «Команды» указателя, и без этого
#     исключения они давали бы ложное срабатывание;
#   - отступные блоки НЕ выбрасываются, и это не недосмотр: иначе копию
#     правила можно было бы спрятать от проверки, сдвинув её на четыре
#     пробела. Команды из отступных блоков в сравнении участвуют, но
#     столкнуться им не с чем — в указателе команды лежат в fenced-блоках;
#   - заголовки выброшены: имя раздела — это то, чем на правило ссылаются,
#     и наказывать за правильную ссылку нельзя;
#   - инлайн-код и цель markdown-ссылки убраны, текст ссылки оставлен;
#   - многобайтовая пунктуация перечислена литералами, а не классом
#     символов: класс с кириллицей в локали C разваливается на байты, и
#     проверка вела бы себя в CI иначе, чем локально;
#   - ASCII-пунктуация снимается через tr, побайтово, и это безопасно: в
#     UTF-8 многобайтовые последовательности не содержат байтов < 0x80;
#   - регистр не сворачивается сознательно: tolower() на кириллице в mawk
#     (а на ubuntu-latest awk — скорее mawk, не gawk) не делает ничего, и
#     локальный gawk давал бы результат, отличный от CI-шного. Окно в
#     десять слов над скопированным абзацем совпадает и без свёртки.
normalize() {
    awk 'BEGIN{inc=0}
         /^```/ {inc=!inc; next}
         inc {next}
         /^[[:space:]]*#/ {next}
         {print}' "$1" \
    | sed -e 's/`[^`]*`/ /g' \
          -e 's/\[\([^]]*\)\]([^)]*)/\1/g' \
          -e 's/—/ /g' -e 's/–/ /g' -e 's/«/ /g' -e 's/»/ /g' \
          -e 's/„/ /g' -e 's/“/ /g' -e 's/…/ /g' -e 's/→/ /g' \
          -e 's/─/ /g' -e 's/│/ /g' -e 's/┴/ /g' -e 's/└/ /g' \
          -e 's/◄/ /g' -e 's/►/ /g' -e 's/▲/ /g' \
    | tr -s '[:punct:][:space:]' ' '
}

# Скользящие окна по COPY_WINDOW слов. Кольцевой буфер в awk и склейка
# строк — никаких операций над символами, поэтому mawk считает то же, что
# gawk.
windows() {
    normalize "$1" | tr ' ' '\n' | grep -v '^$' \
    | awk -v n="$COPY_WINDOW" '{ buf[NR % n] = $0
        if (NR >= n) { s = ""
            for (i = NR - n + 1; i <= NR; i++) s = s (s == "" ? "" : " ") buf[i % n]
            print s } }'
}

if [ -f "$POINTER" ]; then
    # Результат mktemp проверяется, потому что set -e здесь намеренно нет:
    # без проверки пустая подстановка превращает запись в "$COPY_TMP/pointer"
    # в запись в корень ФС, trap вырождается в rm -rf "", а проверка 6
    # сообщает копию с пустой цитатой по каждому файлу правил. Гейт,
    # выдумывающий нарушения, хуже отсутствующего: код 2 — ошибка запуска.
    COPY_TMP="$(mktemp -d)" || {
        printf 'Не удалось создать временный каталог для проверки копий\n' >&2
        exit 2
    }
    trap 'rm -rf "$COPY_TMP"' EXIT

    # Сортировка и сравнение — принудительно в локали C: сравниваются
    # байты, и набор совпадений не зависит от локали запуска.
    LC_ALL=C windows "$POINTER" | LC_ALL=C sort -u > "$COPY_TMP/pointer"

    for rule in "${rules[@]}"; do
        LC_ALL=C windows "$rule" | LC_ALL=C sort -u > "$COPY_TMP/rule"
        LC_ALL=C comm -12 "$COPY_TMP/pointer" "$COPY_TMP/rule" > "$COPY_TMP/common"

        matched="$(grep -c . "$COPY_TMP/common")"
        [ "$matched" -eq 0 ] && continue

        # Подряд идущие окна над одним абзацем совпадают все сразу, и
        # перечислять их значит завалить вывод. Файл называется один раз:
        # первое совпадение по порядку в тексте — оно указывает, где
        # начинается скопированный абзац, — и число остальных.
        first="$(LC_ALL=C windows "$rule" | grep -Fxf "$COPY_TMP/common" -m1)"
        rest=$((matched - 1))

        # Цитата приведена после нормализации: пунктуации в ней нет, и
        # искать её в файле дословным поиском бесполезно — искать надо
        # абзац, который с этих слов начинается. Лечится копия заменой на
        # ссылку, а не правкой обеих сторон.
        if [ "$rest" -gt 0 ]; then
            report "$rule" "копия формулировки из $POINTER: «$first» (и ещё совпадений: $rest)"
        else
            report "$rule" "копия формулировки из $POINTER: «$first»"
        fi
    done
fi

# ------------------------------------------------------------------
printf '\n'
if [ "$VIOLATIONS" -gt 0 ]; then
    printf 'Расхождений: %d. Правила и промпты разъехались.\n' "$VIOLATIONS"
    note 'Правило без работающей ссылки — не источник, а надежда на него.'
    note 'Правило, записанное дважды, — не видимость, а вторая версия.'
    exit 1
fi

printf 'Правила, промпты и указатель сходятся.\n'
exit 0
