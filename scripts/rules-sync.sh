#!/usr/bin/env bash
#
# Домовой — сверка правил шагов работы с промптами и указателем.
#
# ЗАЧЕМ
#
# Правила шагов живут в docs/rules/. На них ссылаются промпты
# .github/workflows/agent-*.yml — шаги агентского цикла, и определения
# субагентов локального режима в .claude/agents/; указатель держит
# .claude/CLAUDE.md. Четыре места, и разъехаться они могут молча: файл
# переименовали — потребитель ссылается в пустоту и агент работает без правил;
# файл добавили — указатель о нём не знает и локальная сессия его не откроет;
# шаг завели без определения — локально его никто не выполнит по правилам.
#
# Проверка механическая именно поэтому. Ссылка, которую никто не проверял, —
# это не источник правил, а надежда на него.
#
# ДВА КЛАССА ОПРЕДЕЛЕНИЙ
#
# В .claude/agents/ живут не только шаги. Класс различается по имени файла:
# step-*.md — шаг работы со своим файлом правил в docs/rules/, любое другое
# *.md — служебный агент, за которым шага нет вовсе (первый такой —
# issue-scout). Второго префикса нет намеренно: файл, не подпавший ни под один
# шаблон, снова не проверялся бы никем, а ровно от этого запись 0021 и
# защищает. Всё, что лежит в каталоге, попадает в один из двух списков.
#
# Требования к классам различаются, и различия перечислены у каждой проверки
# ниже. Отдельно один инвариант, который легко потерять при правке:
# **множество общих правил выводится проходом по шагам, а не по обоим
# классам.** Правилом шага считается файл, к имени которого имя шага сходится
# через дефис, — служебное имя вида reading-scout забрало бы reading.md себе,
# правило перестало бы быть общим, и обязательность ссылки на него молча
# снялась бы со всех потребителей, не уронив ни одного прогона.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Каждая ссылка на docs/rules/*.md из потребителя ведёт в существующий
#      файл. Потребители — промпты .github/workflows/agent-*.yml и определения
#      .claude/agents/*.md обоих классов: битая ссылка на правила стоит
#      одинаково, кем бы её ни оставили.
#   2. Каждый файл правил упомянут хотя бы одним промптом и хотя бы одним
#      определением шага: правило, о котором знает только цикл, для живого
#      режима не существует, и наоборот. Служебные агенты в этот список не
#      входят — правило, упомянутое только ими, шагам недоступно, и краснеть
#      оно обязано по-прежнему. README — указатель, он исключён: на него
#      ссылаются файлы правил, а не потребители.
#   3. Потребитель шага ссылается на правила своего шага: agent-triage.yml и
#      step-triage.md — на triage.md, agent-review.yml — на review-*.md,
#      step-fix-flaky.md — на fix.md. Соответствие выводится из имён файлов, а
#      не задано списком. Со служебного агента правил своего шага не
#      требуется: шага за ним нет. Правило, к чьему имени не сходится ни один
#      шаг, считается общим и обязательно у каждого потребителя обоих
#      классов — так проверяется reading.md.
#   3б. Определение любого класса, которому в tools выдан Bash, подключает
#      границу команд scripts/step-bash-allow.sh — именно хуком PreToolUse, с
#      матчером Bash и непустым списком разрешённого. PostToolUse срабатывает после
#      исполнения и отказать не может, поэтому событие сверяется, а не
#      предполагается. Определение без поля tools — тоже расхождение: без
#      него субагент наследует все инструменты, включая Bash.
#   3в. Верхнеуровневый скаляр фронтматера определения, не заключённый в
#      кавычки, не содержит «: » — двоеточия с пробелом. Для YAML это
#      вложенное отображение, а не текст: разбор падает, харнесс определение
#      не загружает, и тип шага пропадает из доступных, не уронив при этом ни
#      одной проверки репозитория. Закавыченный скаляр двоеточие содержать
#      вправе, и правило без этой оговорки роняло бы законную запись.
#   3г. Вызов границы команд вложен так, как его ждёт харнесс: hooks: на
#      нулевом отступе, PreToolUse: прямым потомком под ним, элемент списка с
#      matcher: Bash под PreToolUse:, вложенный hooks: внутри этого элемента,
#      элемент с type: command под ним — и вызов step-bash-allow.sh лежит
#      именно в этой цепочке. Сверяются значения, а не имена ключей: элемент
#      с матчером другого инструмента границу команд оболочки не даёт, а
#      PreToolUse: из глубины поддерева харнесс не читает. Проверка 3б ищет
#      части блока текстом и к вложенности нечувствительна: блок, съехавший
#      по отступу, но всё ещё разбирающийся как YAML, она проходит целиком, а
#      харнесс хук не подключает. Отказ при этом открытый — шаг остаётся
#      доступен, tools содержит Bash, границы команд у него нет.
#   4. Каждый файл правил указан в .claude/CLAUDE.md.
#   5. Относительные markdown-ссылки внутри docs/rules/*.md ведут в
#      существующие файлы.
#   6. Ни один файл правил не пересказывает .claude/CLAUDE.md: совпадающая
#      формулировка длиной от десяти слов считается копией.
#
# ЧЕГО ЭТА СВЕРКА НЕ ЛОВИТ
#
# Проверки 1–5 смотрят на связи: путь существует, файл упомянут промптом.
# Содержание для них безразлично, и потому копию правила они пропускают —
# ссылка-то на месте. Проверка 6 смотрит на содержание, но и она видит
# только дословное совпадение: пересказ другими словами не ловится вовсе.
# Механически он и недостижим, а делать вид, что достижим, хуже, чем назвать
# границу. Пример прямо в репозитории: список запрещённых подавлений в
# .claude/CLAUDE.md и его пересказ в docs/rules/review-correctness.md —
# порог десяти слов его не видит, а снижать порог ради него значит получить
# ложные тревоги на всём остальном.
#
# Между этими двумя случаями есть третий, и он тоже не ловится: дословная
# копия короче окна. В репозитории таких две — их видно, если поставить
# COPY_WINDOW=9. Перечислены в #73 и лечатся заменой на отсылку, а не
# снижением порога здесь.
#
# Проверка 3в смотрит на симптом, а не на инвариант. Инвариант звучит
# «харнесс загрузил определение», и обвязке он недоступен вовсе: определения
# грузит харнесс, а не CI, и спросить его отсюда нечем. Проверяется один
# способ сломать разбор — тот, на котором уже споткнулись (#97). Мимо неё
# проходят остальные: табуляция в отступе, незакрытая или непарная кавычка,
# двоеточие в самом конце значения, дубль ключа, съехавший отступ, ломающий
# разбор (тот, что разбор переживает, — предмет проверки 3г), отсутствующая
# закрывающая черта фронтматера — и значение, перенесённое на следующую
# строку: признак ищется с привязкой к началу строки, поэтому продолжение
# многострочного plain-скаляра в проверку не попадает вовсе, а «: » ломает
# разбор и там. При принятой в проекте вёрстке по ширине описание однажды
# перенесут, и 3в об этом смолчит. Мимо проходит и всё, что лежит
# не на верхнем уровне: под hooks: лежат команды границы, двоеточие в них
# законно, и признак без привязки к началу строки завалил бы каждое
# определение с подключённой границей. Зелёная 3в означает «этой ловушки
# здесь нет», а не «фронтматер разбирается».
#
# Проверка 3г — того же рода и с той же честной границей. Отступ она считает
# пробелами: табуляция для неё не отступ вовсе, и определение с табуляциями
# она разбирает неверно — как и 3в, не поймав сломанный разбор. Она сверяет
# отношение «вложено глубже», а не точную колонку: элемент с type: command, у
# которого command: съехал от колонки type:, YAML отвергнет, а 3г пропустит —
# пара type: command опознана на первой же строке элемента, и до колонки
# остальных его ключей дело не доходит. Значения type и matcher сверяются
# буквально: штатная запись — type: command и matcher: Bash без кавычек, и на
# законных type: "command" и matcher: "Bash" проверка покраснеет. И, как всё
# здесь, харнесс она не спрашивает: зелёная 3г означает «цепочка вложенности
# на месте», а не «хук подключён».
#
# И ещё одна граница, у самой 3г: «вызов» она опознаёт упоминанием пути в
# поддереве элемента, а не значением ключа command:. Путь, названный в
# хвостовом комментарии рядом с другой командой, цепочку удовлетворит.
# Значение здесь не разбирается намеренно — команды пишутся блочным скаляром
# command: >-, где # обычный текст, и вырезание хвостовых комментариев
# испортило бы ровно те строки, которые проверка читает.
#
# КАК ЗАПУСКАТЬ
#
#   bash scripts/rules-sync.sh              # корень репозитория
#   bash scripts/rules-sync.sh /путь/к/копии
#
# Код возврата: 0 — сходится, 1 — есть расхождения, 2 — ошибка запуска.
#
set -uo pipefail

ROOT="${1:-}"
if [ -z "$ROOT" ]; then
    ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fi

if [ ! -d "$ROOT" ]; then
    printf 'Не найден каталог: %s\n' "$ROOT" >&2
    exit 2
fi

cd "$ROOT" || exit 2

RULES_DIR='docs/rules'
AGENTS_DIR='.claude/agents'
POINTER='.claude/CLAUDE.md'

if [ ! -d "$RULES_DIR" ]; then
    printf 'Не найден каталог правил: %s/%s\n' "$ROOT" "$RULES_DIR" >&2
    exit 2
fi

VIOLATIONS=0

report() {
    # Формат GitHub Actions: сообщение попадает в аннотации к файлу.
    printf '::error file=%s::%s\n' "$1" "$2"
    VIOLATIONS=$((VIOLATIONS + 1))
}

note() {
    printf '  %s\n' "$1"
}

# Потребители правил и сами правила. Все три списка берутся из файловой
# системы: источник истины — то, что лежит в репозитории, а не перечисление
# внутри скрипта.
#
# Потребителей два класса. Промпт .github/workflows/agent-<шаг>.yml — процесс
# агентского цикла; определение .claude/agents/step-<шаг>.md — субагент
# локального режима. Шаг выводится снятием префикса, одинаково для обоих:
# соответствие «потребитель → правила своего шага» выводится из имён, а не
# задаётся списком, который сам разъезжается.
#
# Определения делятся ещё раз, и тоже по имени: step-*.md — шаги, всё
# остальное в каталоге — служебные агенты. Деление производное, а не по
# второму префиксу: непроверяемых файлов в каталоге не остаётся вовсе.
prompts=()
while IFS= read -r f; do
    [ -n "$f" ] && prompts+=("$f")
done < <(find .github/workflows -maxdepth 1 -name 'agent-*.yml' 2>/dev/null | sort)

agents=()
while IFS= read -r f; do
    [ -n "$f" ] && agents+=("$f")
done < <(find "$AGENTS_DIR" -maxdepth 1 -name 'step-*.md' 2>/dev/null | sort)

services=()
while IFS= read -r f; do
    [ -n "$f" ] && services+=("$f")
done < <(find "$AGENTS_DIR" -maxdepth 1 -name '*.md' ! -name 'step-*.md' 2>/dev/null | sort)

rules=()
while IFS= read -r f; do
    [ -n "$f" ] && rules+=("$f")
done < <(find "$RULES_DIR" -maxdepth 1 -name '*.md' 2>/dev/null | sort)

if [ "${#prompts[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного .github/workflows/agent-*.yml\n' >&2
    exit 2
fi

# Пустой список шагов — сломанный клон: шаги обязаны быть. Пустой список
# служебных агентов — законное состояние, и кода возврата за него нет.
if [ "${#agents[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного %s/step-*.md\n' "$AGENTS_DIR" >&2
    exit 2
fi

if [ "${#rules[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного файла правил в %s\n' "$RULES_DIR" >&2
    exit 2
fi

printf 'Правила: %d файл(ов), промпты: %d, определения шагов: %d, служебные агенты: %d\n\n' \
    "${#rules[@]}" "${#prompts[@]}" "${#agents[@]}" "${#services[@]}"

# Оба класса вместе — там, где требование к ним одинаково. Пустой массив
# разворачивается через ${x[@]+…}: под set -u пустой "${x[@]}" в bash до 4.4
# ошибка, а не пустота, и поведение разошлось бы между CI и локальной машиной.
definitions=("${agents[@]}" ${services[@]+"${services[@]}"})

# Ссылки на файлы правил, встречающиеся в файле потребителя.
refs_in() {
    grep -ohE 'docs/rules/[A-Za-z0-9._-]+\.md' "$1" | sort -u
}

# Шаг потребителя: agent-triage.yml → triage, step-fix-flaky.md → fix-flaky.
step_of() {
    base="$(basename "$1")"
    base="${base%.yml}"
    base="${base%.md}"
    base="${base#agent-}"
    base="${base#step-}"
    printf '%s' "$base"
}

# Правила шага: имена совпадают или одно начинается с другого через дефис.
# Так review получает review-correctness.md и review-security.md, а
# fix-flaky — fix.md: оценка флаки часть шага починки и живёт по его
# правилам, отдельного файла правил у неё нет.
rules_of_step() {
    step="$1"
    for rule in "${rules[@]}"; do
        base="$(basename "$rule" .md)"
        [ "$base" = 'README' ] && continue
        if [ "$base" = "$step" ] \
            || [ "${base#"$step"-}" != "$base" ] \
            || [ "${step#"$base"-}" != "$step" ]; then
            printf '%s\n' "$rule"
        fi
    done
}

# ------------------------------------------------------------------
# Проверка 1. Ссылки потребителей ведут в существующие файлы.
#
# Оба класса определений: битая ссылка вида docs/rules/scout.md из служебного
# агента осталась бы иначе невидимой, и «непроверяемых файлов в каталоге не
# остаётся» перестало бы быть правдой.
# ------------------------------------------------------------------
for consumer in "${prompts[@]}" "${definitions[@]}"; do
    while IFS= read -r ref; do
        [ -z "$ref" ] && continue
        if [ ! -f "$ref" ]; then
            report "$consumer" "ссылка на несуществующие правила: $ref"
        fi
    done < <(refs_in "$consumer")
done

# ------------------------------------------------------------------
# Проверка 2. Каждый файл правил упомянут хотя бы одним промптом и хотя бы
# одним определением шага.
#
# Два условия, а не одно: правило, о котором знает только цикл, для живого
# режима не существует — и наоборот. README исключён намеренно: это
# указатель, и ссылаются на него файлы правил.
#
# Массив здесь из шагов, а не из обоих классов: правило, упомянутое только
# служебным агентом, ни одному шагу не досталось, и деление каталога надвое
# эту половину проверки ослабить не должно. Побочный, но полезный эффект —
# опечатка в префиксе (stpe-triage.md) тихо переводит шаг в служебные, и
# ловится она именно здесь: правила такого шага перестают быть упомянуты.
# ------------------------------------------------------------------
for rule in "${rules[@]}"; do
    base="$(basename "$rule")"
    [ "$base" = 'README.md' ] && continue
    if ! grep -qF "$rule" "${prompts[@]}"; then
        report "$rule" "файл правил не упомянут ни одним промптом agent-*.yml"
    fi
    if ! grep -qF "$rule" "${agents[@]}"; then
        report "$rule" "файл правил не упомянут ни одним определением step-*.md"
    fi
done

# ------------------------------------------------------------------
# Проверка 3. Потребитель шага ссылается на правила своего шага.
# ------------------------------------------------------------------
check_own_rules() {
    noun="$1"
    shift
    for consumer in "$@"; do
        step="$(step_of "$consumer")"

        expected=()
        while IFS= read -r rule; do
            [ -n "$rule" ] && expected+=("$rule")
        done < <(rules_of_step "$step")

        if [ "${#expected[@]}" -eq 0 ]; then
            report "$consumer" "у шага «$step» нет файла правил в $RULES_DIR"
            continue
        fi

        for rule in "${expected[@]}"; do
            if ! grep -qF "$rule" "$consumer"; then
                report "$consumer" "$noun шага «$step» не ссылается на свои правила: $rule"
            fi
        done
    done
}

# Только шаги: у служебного агента шага нет, и вывод «у шага «issue-scout» нет
# файла правил» был бы требованием завести правило под каждый вызов модели.
check_own_rules 'промпт' "${prompts[@]}"
check_own_rules 'определение' "${agents[@]}"

# ------------------------------------------------------------------
# Проверка 3а. Правило, не принадлежащее ни одному шагу, обязательно у
# каждого потребителя.
#
# Такое правило в каталоге одно — reading.md, «Любой шаг». Своего процесса
# у него нет именно потому, что нужно всем: промпт или определение, в
# котором его нет, — это шаг, чей агент правило не откроет. Список общих
# правил не перечисляется, а выводится: файл правил, к чьему имени не
# сходится ни один шаг, общий по построению.
# ------------------------------------------------------------------
# Правила, у которых есть свой шаг, собираются один раз проходом по
# потребителям: обратный порядок — по правилу на каждого потребителя —
# стоил бы вдвое больше подпроцессов на том же результате.
#
# Проход идёт по шагам, и служебных агентов в нём нет намеренно. Это не
# проверка, а вывод множества общих правил: имя вида reading-scout сходится с
# reading.md через дефис, забрало бы его в owned_rules — и требование общего
# правила молча снялось бы со всех потребителей разом.
owned_rules=''
for consumer in "${prompts[@]}" "${agents[@]}"; do
    while IFS= read -r rule; do
        [ -n "$rule" ] && owned_rules="$owned_rules$rule"$'\n'
    done < <(rules_of_step "$(step_of "$consumer")")
done

general=()
for rule in "${rules[@]}"; do
    base="$(basename "$rule" .md)"
    [ "$base" = 'README' ] && continue

    case "$owned_rules" in
        *"$rule"$'\n'*) ;;
        *) general+=("$rule") ;;
    esac
done

for rule in "${general[@]}"; do
    note "общее правило: $rule — обязательно у каждого потребителя"
    for consumer in "${prompts[@]}" "${definitions[@]}"; do
        if ! grep -qF "$rule" "$consumer"; then
            report "$consumer" "не ссылается на общее правило: $rule"
        fi
    done
done

# ------------------------------------------------------------------
# Проверка 3б. Определение, которому выдан Bash, подключает границу команд.
#
# Без этой проверки блок hooks можно убрать, опечататься в пути или в
# матчере — и субагент получит Bash целиком, а все проверки останутся
# зелёными. Сам скрипт границы из CI не запускается (его зовёт PreToolUse),
# поэтому единственное место, где связь «определение → граница» вообще
# кем-то проверяется, — здесь.
# ------------------------------------------------------------------
BOUNDARY='scripts/step-bash-allow.sh'

# ------------------------------------------------------------------
# Проверка 3в. Фронтматер определения не сломан двоеточием.
#
# Определение, которое харнесс не может загрузить, до этой проверки проходило
# все проверки репозитория зелёным: связи на месте, ссылки на месте, код 0.
# Наблюдено на #97 — в описание шага попало двоеточие с пробелом, для YAML это
# вложенное отображение вместо текста, разбор упал, тип шага пропал из
# доступных, и причину нашли только прогнав фронтматер парсером вручную.
# Тире и двоеточия в описаниях — норма стиля этого проекта, так что ловушка
# сработала бы снова на любой правке описания.
#
# Проверка идёт тем же проходом, что и 3б: фронтматер вытаскивается один раз.
# Стоит она первой в теле цикла намеренно — ниже по циклу два continue, и за
# ними определение без Bash проверку фронтматера не проходило бы вовсе.
# ------------------------------------------------------------------
# Форма определения проверяется у обоих классов: Bash без границы команд,
# сломанный двоеточием фронтматер и съехавший блок хука ломают служебного
# агента ровно так же, как шаг.
for agent in "${definitions[@]}"; do
    # Frontmatter — от первой строки --- до второй. Тело определения не
    # смотрим: инструменты и хуки задаются только в шапке.
    front="$(sed -n '2,/^---$/p' "$agent")"

    # Проверка 3в. Ключи нулевого отступа — и только они: вложенное значение
    # разбирается в своём контексте, а команды границы под hooks: двоеточия
    # содержат законно.
    while IFS= read -r line; do
        key="${line%%:*}"
        value="${line#*:}"
        # Ведущие пробелы снимаются: сравнивается сам скаляр.
        value="${value#"${value%%[![:space:]]*}"}"

        # Пустое значение — вложенное отображение (hooks:), скаляра нет.
        [ -z "$value" ] && continue

        case "$value" in
            # Кавычки снимают с двоеточия роль разделителя, блочный скаляр
            # (> или |) — тем более: он кончается концом блока, а не строки.
            "'"*|'"'*|'>'*|'|'*) continue ;;
            *': '*)
                report "$agent" "фронтматер: незакавыченное значение ключа «$key» содержит «: » — YAML разберёт его как вложенное отображение, и харнесс определение не загрузит"
                ;;
        esac
    done < <(printf '%s\n' "$front" | grep -E '^[A-Za-z_][A-Za-z0-9_-]*:')

    # Поле tools в любой форме: строкой, списком YAML или в скобках.
    # Кончается оно на следующем ключе верхнего уровня.
    tools="$(printf '%s' "$front" | sed -n '/^tools:/,/^[A-Za-z]/p')"

    if [ -z "$tools" ]; then
        # Отсутствие tools означает наследование всех инструментов, включая
        # Bash. Пропустить такое определение молча значит снять с него
        # требование границы — то самое, против чего эта проверка написана.
        report "$agent" "в определении нет поля tools: субагент наследует все инструменты, включая Bash, и граница команд к нему не предъявляется"
        continue
    fi

    printf '%s' "$tools" | grep -qE '(^|[^A-Za-z])Bash([^A-Za-z]|$)' || continue

    # Вызов границы должен лежать под PreToolUse. PostToolUse срабатывает
    # после исполнения и отказать уже не может: подмена события выключает
    # границу, не тронув ни путь, ни матчер, ни список.
    pre="$(printf '%s' "$front" | sed -n '/^[[:space:]]*PreToolUse:/,$p')"

    if [ -z "$pre" ]; then
        report "$agent" "определению выдан Bash, но хука PreToolUse нет: граница команд не подключена"
        continue
    fi

    if ! printf '%s' "$pre" | grep -qF "$BOUNDARY"; then
        report "$agent" "определению выдан Bash, но граница команд не подключена под PreToolUse: нет вызова $BOUNDARY"
        continue
    fi

    if ! printf '%s' "$pre" | grep -qE '^[[:space:]]*-[[:space:]]*matcher:[[:space:]]*Bash[[:space:]]*$'; then
        report "$agent" "граница команд подключена без матчера Bash: хук не сработает на вызовах оболочки"
    fi

    # Список разрешённого — кавычки после вызова скрипта. Пустой список хук
    # и сам отвергнет, но узнать об этом на прогоне сверки дешевле, чем на
    # первом же вызове шага.
    if ! printf '%s' "$pre" | sed -n "/step-bash-allow\.sh/,\$p" | grep -qE "'[^']+'"; then
        report "$agent" "граница команд подключена без списка разрешённых команд"
    fi

    # --------------------------------------------------------------
    # Проверка 3г. Вызов границы вложен туда, где его ждёт харнесс.
    #
    # Всё выше по циклу ищет части блока хука текстом и к вложенности
    # нечувствительно. Блок, съехавший по отступу, но всё ещё разбирающийся
    # как YAML, проходит эти проверки целиком — а харнесс хук не подключает,
    # и шаг остаётся с Bash без границы команд.
    #
    # Цепочка считается от вызова границы, а не «где-то во фронтматере есть
    # правильная форма»: рядом с настоящим блоком достаточно приписать
    # безупречный по форме пустой, и проверка зазеленела бы на выключенной
    # границе.
    #
    # «Вызов» при этом — упоминание пути в поддереве элемента, а не значение
    # ключа command:. Путь в хвостовом комментарии рядом с другой командой
    # цепочку удовлетворит; значение не разбирается намеренно — команды
    # записаны блочным скаляром, где # обычный текст.
    #
    # Отступ — пробелы, элемент списка приводится к колонке своего первого
    # ключа. Требование «вложен строго глубже» предъявляется ключам, но не
    # элементам списка: в YAML список вправе стоять на отступе своего ключа,
    # и правило без этой оговорки завалило бы законную запись.
    # --------------------------------------------------------------
    nesting="$(printf '%s\n' "$front" | awk -v boundary="$BOUNDARY" '
        function keyof(s,   p) {
            if (s ~ /^[A-Za-z_][A-Za-z0-9_-]*:/) {
                p = index(s, ":")
                return substr(s, 1, p - 1)
            }
            return ""
        }
        # Элементы списка под ключом: первый задаёт колонку дефиса, остальные
        # стоят на ней же. Границы элемента нужны, чтобы искать вызов границы
        # в поддереве, а не во всём фронтматере.
        function items(after, col,   k, d) {
            IN = 0; IEND = after; d = -1
            for (k = after + 1; k <= N; k++) {
                if (SI[k] < col) break
                if (DASH[k] < 0 && IND[k] <= col) break
                if (DASH[k] >= col && d < 0) d = DASH[k]
                if (d >= 0 && DASH[k] == d) { IN++; IS[IN] = k }
                IEND = k
            }
            return IN
        }
        # Элемент, в поддереве которого встречается искомое. Пределы найденного
        # остаются в OS и OE.
        function owner(mark,   j, s, e, k) {
            for (j = 1; j <= IN; j++) {
                s = IS[j]; e = (j < IN ? IS[j + 1] - 1 : IEND)
                for (k = s; k <= e; k++) {
                    if (index(TXT[k], mark) > 0) { OS = s; OE = e; return j }
                }
            }
            return 0
        }
        {
            sub(/\r$/, "")
            if ($0 ~ /^[ ]*$/) next
            # Комментарий YAML — не ключ и не элемент списка. Строка «#» в
            # колонке 0 иначе выглядела бы концом блока hooks: и обрывала
            # обход на законном определении, которое харнесс грузит.
            if ($0 ~ /^[ ]*#/) next
            p = match($0, /[^ ]/)
            col = p - 1
            rest = substr($0, p)
            d = -1
            if (rest ~ /^-([ ]|$)/) {
                d = col
                if (match(rest, /^-[ ]+/)) {
                    col = col + RLENGTH
                    rest = substr(rest, RLENGTH + 1)
                } else {
                    col = col + 1
                    rest = ""
                }
            }
            N++
            TXT[N] = $0
            IND[N] = col
            DASH[N] = d
            SI[N] = (d >= 0 ? d : col)
            KEY[N] = keyof(rest)
            VAL[N] = ""
            if (KEY[N] != "") {
                v = substr(rest, length(KEY[N]) + 2)
                gsub(/^[ ]+|[ ]+$/, "", v)
                VAL[N] = v
            }
        }
        END {
            top = 0
            for (k = 1; k <= N; k++) {
                if (DASH[k] < 0 && IND[k] == 0 && KEY[k] == "hooks") { top = k; break }
            }
            if (top == 0) {
                print "блок hooks: не лежит на верхнем уровне фронтматера — харнесс ищет его там и хук не подключит"
                exit
            }
            # PreToolUse: обязан быть прямым потомком блока hooks:, а не
            # лежать где-то в его поддереве: харнесс читает hooks.PreToolUse и
            # глубже не заглядывает. Колонка прямого потомка не задаётся
            # числом — она берётся с первого ключа под hooks:, иначе правило
            # завалило бы законный отступ, отличный от двух пробелов.
            child = -1
            for (k = top + 1; k <= N && SI[k] > 0; k++) {
                if (DASH[k] < 0 && KEY[k] != "") { child = IND[k]; break }
            }
            pre = 0
            deeper = 0
            for (k = top + 1; k <= N && SI[k] > 0; k++) {
                if (DASH[k] < 0 && KEY[k] == "PreToolUse") {
                    if (IND[k] == child) { pre = k; break }
                    deeper = 1
                }
            }
            if (pre == 0) {
                if (deeper == 1) {
                    print "ключ PreToolUse: лежит глубже прямого потомка блока hooks: — харнесс читает hooks.PreToolUse и глубже не заглядывает"
                } else {
                    print "ключ PreToolUse: не вложен в блок hooks: верхнего уровня"
                }
                exit
            }
            if (items(pre, IND[pre]) == 0) {
                print "под ключом PreToolUse: нет списка матчеров"
                exit
            }
            if (owner(boundary) == 0) {
                print "вызов границы лежит вне списка под ключом PreToolUse — харнесс подключит хук не туда"
                exit
            }
            istart = OS; iend = OE; icol = IND[istart]
            # Сверяется значение матчера, а не одно имя ключа: рядом с
            # элементом, к которому подвешена граница, довольно положить
            # элемент с matcher: Bash и безобидной командой — текстовая
            # сверка матчера выше по циклу находит его и зеленеет, а харнесс
            # вешает границу на тот инструмент, который назван здесь.
            hasmatcher = (KEY[istart] == "matcher" && VAL[istart] == "Bash")
            hk = (KEY[istart] == "hooks" ? istart : 0)
            for (k = istart + 1; k <= iend; k++) {
                if (DASH[k] < 0 && IND[k] == icol) {
                    if (KEY[k] == "matcher" && VAL[k] == "Bash") hasmatcher = 1
                    if (KEY[k] == "hooks" && hk == 0) hk = k
                }
            }
            if (hasmatcher == 0) {
                print "в элементе списка с вызовом границы нет matcher: Bash — хук подключён не к вызовам оболочки"
                exit
            }
            if (hk == 0) {
                print "в элементе с матчером нет вложенного ключа hooks — вызов границы лежит вне списка команд матчера"
                exit
            }
            if (items(hk, IND[hk]) == 0 || owner(boundary) == 0) {
                print "вызов границы лежит вне элемента списка под вложенным ключом hooks"
                exit
            }
            hastype = (KEY[OS] == "type" && VAL[OS] == "command")
            for (k = OS + 1; k <= OE; k++) {
                if (DASH[k] < 0 && IND[k] == IND[OS] && KEY[k] == "type" && VAL[k] == "command") hastype = 1
            }
            if (hastype == 0) {
                print "в элементе с вызовом границы нет пары type: command"
            }
        }
    ')"

    if [ -n "$nesting" ]; then
        report "$agent" "$nesting"
    fi
done

# ------------------------------------------------------------------
# Проверка 4. Каждый файл правил указан в .claude/CLAUDE.md.
#
# Указатель — единственное, что читает локальная сессия, не заходя в
# .github/**. Файл правил, которого в нём нет, для живого режима не
# существует.
# ------------------------------------------------------------------
if [ ! -f "$POINTER" ]; then
    report "$POINTER" "не найден указатель на правила"
else
    for rule in "${rules[@]}"; do
        [ "$(basename "$rule")" = 'README.md' ] && continue
        if ! grep -qF "$rule" "$POINTER"; then
            report "$POINTER" "правила не указаны в файле правил проекта: $rule"
        fi
    done
fi

# ------------------------------------------------------------------
# Проверка 5. Относительные ссылки внутри правил ведут в существующие
# файлы. Правила ссылаются на записи решений и друг на друга — битая
# ссылка здесь стоит того же, что битая ссылка из промпта.
# ------------------------------------------------------------------
for rule in "${rules[@]}"; do
    dir="$(dirname "$rule")"
    while IFS= read -r target; do
        [ -z "$target" ] && continue
        case "$target" in
            http*|'#'*) continue ;;
        esac
        # Якорь после пути к файлу отбрасывается: проверяется файл.
        target="${target%%#*}"
        [ -z "$target" ] && continue
        resolved="$dir/$target"
        # Нормализация ../ вручную: realpath есть не в каждом окружении, а
        # путей здесь единицы.
        while printf '%s' "$resolved" | grep -q '/[^/][^/]*/\.\./'; do
            resolved="$(printf '%s' "$resolved" | sed -E 's#/[^/]+/\.\./#/#')"
        done
        if [ ! -e "$resolved" ]; then
            report "$rule" "битая ссылка: $target"
        fi
    done < <(grep -ohE '\]\([^)]+\.md[^)]*\)' "$rule" \
        | sed -E 's/^\]\(//; s/\)$//' | sort -u)
done

# ------------------------------------------------------------------
# Проверка 6. Файл правил не пересказывает .claude/CLAUDE.md.
#
# docs/rules/README.md формулирует инвариант: правила шагов — слой поверх
# CLAUDE.md, а не замена ему; где правило уже записано в указателе, здесь
# стоит ссылка. Копия правила хуже отсутствующей ссылки: ссылку видно, а
# копия разъезжается молча — поправили одну сторону, и агент читает две
# разные версии одного правила, не зная об этом.
#
# Постановка обратная сверке двух копий. Сверять побайтово пришлось бы,
# разметив блоки маркерами, — а это превращает CLAUDE.md в генерируемый
# файл. Здесь копии просто запрещены: лечится замена копии на ссылку, то
# есть убирается причина, а не последствие.
#
# Совпадением считается окно в десять слов, встречающееся и в указателе, и
# в файле правил. Порог замерен на репозитории: окно из восьми слов даёт
# попадания в описании назначения каталога в README.md, а это не правило;
# окно из десяти — только настоящие копии. Порог выбран так, чтобы каждое
# попадание было тем, с которым человек согласится: первое ложное — это
# место, где заводится маркер-исключение, а исключений здесь нет.
# Совпадение целого предложения не годится: переписанная пунктуация его
# обходит, а окно — нет.
# ------------------------------------------------------------------
COPY_WINDOW=10

# Нормализация текста перед нарезкой. Из markdown остаётся проза:
#   - fenced-блоки выброшены: код не формулировка правила, а команду вроде
#     `dotnet build` файл шага законно повторяет — в implement.md стоят те
#     же четыре команды, что в разделе «Команды» указателя, и без этого
#     исключения они давали бы ложное срабатывание;
#   - отступные блоки НЕ выбрасываются, и это не недосмотр: иначе копию
#     правила можно было бы спрятать от проверки, сдвинув её на четыре
#     пробела. Команды из отступных блоков в сравнении участвуют, но
#     столкнуться им не с чем — в указателе команды лежат в fenced-блоках;
#   - заголовки выброшены: имя раздела — это то, чем на правило ссылаются,
#     и наказывать за правильную ссылку нельзя;
#   - инлайн-код и цель markdown-ссылки убраны, текст ссылки оставлен;
#   - многобайтовая пунктуация перечислена литералами, а не классом
#     символов: класс с кириллицей в локали C разваливается на байты, и
#     проверка вела бы себя в CI иначе, чем локально;
#   - ASCII-пунктуация снимается через tr, побайтово, и это безопасно: в
#     UTF-8 многобайтовые последовательности не содержат байтов < 0x80;
#   - регистр не сворачивается сознательно: tolower() на кириллице в mawk
#     (а на ubuntu-latest awk — скорее mawk, не gawk) не делает ничего, и
#     локальный gawk давал бы результат, отличный от CI-шного. Окно в
#     десять слов над скопированным абзацем совпадает и без свёртки.
normalize() {
    awk 'BEGIN{inc=0}
         /^```/ {inc=!inc; next}
         inc {next}
         /^[[:space:]]*#/ {next}
         {print}' "$1" \
    | sed -e 's/`[^`]*`/ /g' \
          -e 's/\[\([^]]*\)\]([^)]*)/\1/g' \
          -e 's/—/ /g' -e 's/–/ /g' -e 's/«/ /g' -e 's/»/ /g' \
          -e 's/„/ /g' -e 's/“/ /g' -e 's/…/ /g' -e 's/→/ /g' \
          -e 's/─/ /g' -e 's/│/ /g' -e 's/┴/ /g' -e 's/└/ /g' \
          -e 's/◄/ /g' -e 's/►/ /g' -e 's/▲/ /g' \
    | tr -s '[:punct:][:space:]' ' '
}

# Скользящие окна по COPY_WINDOW слов. Кольцевой буфер в awk и склейка
# строк — никаких операций над символами, поэтому mawk считает то же, что
# gawk.
windows() {
    normalize "$1" | tr ' ' '\n' | grep -v '^$' \
    | awk -v n="$COPY_WINDOW" '{ buf[NR % n] = $0
        if (NR >= n) { s = ""
            for (i = NR - n + 1; i <= NR; i++) s = s (s == "" ? "" : " ") buf[i % n]
            print s } }'
}

if [ -f "$POINTER" ]; then
    # Результат mktemp проверяется, потому что set -e здесь намеренно нет:
    # без проверки пустая подстановка превращает запись в "$COPY_TMP/pointer"
    # в запись в корень ФС, trap вырождается в rm -rf "", а проверка 6
    # сообщает копию с пустой цитатой по каждому файлу правил. Гейт,
    # выдумывающий нарушения, хуже отсутствующего: код 2 — ошибка запуска.
    COPY_TMP="$(mktemp -d)" || {
        printf 'Не удалось создать временный каталог для проверки копий\n' >&2
        exit 2
    }
    trap 'rm -rf "$COPY_TMP"' EXIT

    # Сортировка и сравнение — принудительно в локали C: сравниваются
    # байты, и набор совпадений не зависит от локали запуска.
    LC_ALL=C windows "$POINTER" | LC_ALL=C sort -u > "$COPY_TMP/pointer"

    for rule in "${rules[@]}"; do
        LC_ALL=C windows "$rule" | LC_ALL=C sort -u > "$COPY_TMP/rule"
        LC_ALL=C comm -12 "$COPY_TMP/pointer" "$COPY_TMP/rule" > "$COPY_TMP/common"

        matched="$(grep -c . "$COPY_TMP/common")"
        [ "$matched" -eq 0 ] && continue

        # Подряд идущие окна над одним абзацем совпадают все сразу, и
        # перечислять их значит завалить вывод. Файл называется один раз:
        # первое совпадение по порядку в тексте — оно указывает, где
        # начинается скопированный абзац, — и число остальных.
        first="$(LC_ALL=C windows "$rule" | grep -Fxf "$COPY_TMP/common" -m1)"
        rest=$((matched - 1))

        # Цитата приведена после нормализации: пунктуации в ней нет, и
        # искать её в файле дословным поиском бесполезно — искать надо
        # абзац, который с этих слов начинается. Лечится копия заменой на
        # ссылку, а не правкой обеих сторон.
        if [ "$rest" -gt 0 ]; then
            report "$rule" "копия формулировки из $POINTER: «$first» (и ещё совпадений: $rest)"
        else
            report "$rule" "копия формулировки из $POINTER: «$first»"
        fi
    done
fi

# ------------------------------------------------------------------
printf '\n'
if [ "$VIOLATIONS" -gt 0 ]; then
    printf 'Расхождений: %d. Правила и промпты разъехались.\n' "$VIOLATIONS"
    note 'Правило без работающей ссылки — не источник, а надежда на него.'
    note 'Правило, записанное дважды, — не видимость, а вторая версия.'
    exit 1
fi

printf 'Правила, промпты, определения и указатель сходятся.\n'
exit 0
