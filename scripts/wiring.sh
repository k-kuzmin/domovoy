#!/usr/bin/env bash
#
# Домовой — сверка обвязки: каждая проверка из scripts/ подключена к CI.
#
# ЗАЧЕМ
#
# Гейт целостности проверяет дифф, guard.test.sh проверяет гейт, rules-sync.sh
# сверяет правила с промптами. Все они лежат в scripts/ и запускаются шагами
# workflow — и ровно этот провод до сих пор не проверял никто. Шаг убрали при
# правке — скрипт остаётся в репозитории, выглядит работающим и не запускается
# никогда. Проверка, которую перестали запускать, хуже отсутствующей: она
# создаёт видимость.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Каждый scripts/*.sh вызывается хотя бы одним workflow — или освобождён
#      маркером с причиной (ниже).
#   2. Маркер освобождения снабжён причиной, а не поставлен молча.
#   3. Каждый вызов bash scripts/… из workflow ведёт в существующий файл —
#      зеркальный случай: скрипт переименовали, шаг остался.
#
# Оба списка берутся из файловой системы, а не задаются перечислением здесь:
# перечисление — копия, и разъезжается она так же молча.
#
# ОСВОБОЖДЕНИЕ
#
# Скрипт, которому в CI делать нечего, объявляет это в своей шапке:
#
#   # БЕЗ ОБВЯЗКИ: ручной инструмент под токеном с правом записи.
#
# Причина обязательна и проверяется на длину. Маркер без причины — то же
# молчаливое исключение, только с оправданием.
#
# ЧЕГО ЭТА СВЕРКА НЕ ЛОВИТ
#
# Собственный шаг она защитить не может: удалили шаг с wiring.sh — никто не
# запустится и никто не пожалуется. Шаг с wiring.test.sh она поймает, свой —
# нет. Не ловит она и прямой push в main мимо PR: работа в CI на этом событии
# идёт, но коммит к тому моменту уже в ветке. Оба случая закрываются не
# скриптом, а ревью человека и защитой ветки.
#
# Вызовом считается только вызов из workflow. Скрипт, который зовёт другой
# скрипт, а не шаг, для этой сверки не подключён — и это намеренно: цепочка
# начинается в CI, и проверять надо её начало. Такому помощнику нужен маркер
# с причиной вида «вызывается из guard.sh».
#
# КАК ЗАПУСКАТЬ
#
#   bash scripts/wiring.sh              # корень репозитория
#   bash scripts/wiring.sh /путь/к/копии
#
# Код возврата: 0 — сходится, 1 — есть расхождения, 2 — ошибка запуска.
#
set -uo pipefail

ROOT="${1:-}"
if [ -z "$ROOT" ]; then
    ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fi

if [ ! -d "$ROOT" ]; then
    printf 'Не найден каталог: %s\n' "$ROOT" >&2
    exit 2
fi

cd "$ROOT" || exit 2

SCRIPTS_DIR='scripts'
WORKFLOWS_DIR='.github/workflows'
MARKER='БЕЗ ОБВЯЗКИ:'
# Объявлением считается только комментарий, начинающийся с маркера. Иначе
# маркер, приведённый в шапке как пример — вот как в этом файле выше, —
# освободил бы от обвязки саму сверку.
MARKER_LINE="^#[[:space:]]*$MARKER"

# Причина короче этого — отписка. Считается в байтах, а не в символах: locale
# на разных машинах разный, а кириллица в UTF-8 занимает по два байта, так что
# 24 байта — это примерно двенадцать букв.
REASON_MINIMUM=24

if [ ! -d "$SCRIPTS_DIR" ]; then
    printf 'Не найден каталог скриптов: %s/%s\n' "$ROOT" "$SCRIPTS_DIR" >&2
    exit 2
fi

scripts=()
while IFS= read -r f; do
    [ -n "$f" ] && scripts+=("$f")
done < <(find "$SCRIPTS_DIR" -maxdepth 1 -name '*.sh' 2>/dev/null | sort)

workflows=()
while IFS= read -r f; do
    [ -n "$f" ] && workflows+=("$f")
done < <(find "$WORKFLOWS_DIR" -maxdepth 1 \( -name '*.yml' -o -name '*.yaml' \) \
    2>/dev/null | sort)

if [ "${#scripts[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного скрипта в %s\n' "$SCRIPTS_DIR" >&2
    exit 2
fi

if [ "${#workflows[@]}" -eq 0 ]; then
    printf 'Не найдено ни одного workflow в %s\n' "$WORKFLOWS_DIR" >&2
    exit 2
fi

VIOLATIONS=0

report() {
    # Формат GitHub Actions: сообщение попадает в аннотации к файлу.
    printf '::error file=%s::%s\n' "$1" "$2"
    VIOLATIONS=$((VIOLATIONS + 1))
}

note() {
    printf '  %s\n' "$1"
}

printf 'Скриптов: %d, workflow: %d\n\n' "${#scripts[@]}" "${#workflows[@]}"

# Вызовы, найденные в workflow. Строки-комментарии выброшены до поиска:
# закомментированный шаг — самый правдоподобный способ обмануть текстовый
# поиск, имя в файле есть, а запуска нет.
#
# Формы вызова: `bash scripts/x.sh`, `sh scripts/x.sh`, `./scripts/x.sh`, в том
# числе с префиксом переменных окружения и внутри блока `run: |`.
calls_in() {
    sed -E 's/^[[:space:]]*#.*$//' "$1" \
        | grep -ohE '((bash|sh)[[:space:]]+(\./)?|\./)scripts/[A-Za-z0-9._-]+\.sh' \
        | grep -ohE 'scripts/[A-Za-z0-9._-]+\.sh' \
        | sort -u
}

ALL_CALLS=''
for workflow in "${workflows[@]}"; do
    while IFS= read -r call; do
        [ -z "$call" ] && continue
        ALL_CALLS="$ALL_CALLS$call"$'\n'
    done < <(calls_in "$workflow")
done

is_called() {
    printf '%s' "$ALL_CALLS" | grep -qxF "$1"
}

# ------------------------------------------------------------------
# Проверки 1 и 2. Каждый скрипт вызывается — либо освобождён с причиной.
# ------------------------------------------------------------------
for script in "${scripts[@]}"; do
    # Маркер ищется только в шапке: строка «БЕЗ ОБВЯЗКИ» в теле скрипта — это
    # текст сообщения или проверка вроде этой, а не объявление о себе.
    marker_line="$(head -n 40 "$script" | grep -m1 -E "$MARKER_LINE" || true)"

    if [ -z "$marker_line" ]; then
        if ! is_called "$script"; then
            report "$script" "ни один workflow не вызывает: $script"
            note 'Шаг убрали, а проверка осталась лежать — значит, её больше нет.'
        fi
        continue
    fi

    reason="${marker_line#*"$MARKER"}"
    # Пробелы по краям убираются, чтобы «БЕЗ ОБВЯЗКИ:    » не сошло за причину.
    reason="$(printf '%s' "$reason" | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//')"
    reason_length="$(printf '%s' "$reason" | wc -c)"

    if [ "$reason_length" -lt "$REASON_MINIMUM" ]; then
        report "$script" "маркер освобождения без причины: $script"
        note 'Освобождение без объяснения — то же молчаливое исключение.'
        continue
    fi

    if is_called "$script"; then
        printf '  освобождение устарело: %s вызывается, маркер пора снять\n' "$script"
        continue
    fi

    printf '  освобождён: %s — %s\n' "$script" "$reason"
done

# ------------------------------------------------------------------
# Проверка 3. Вызов ведёт в существующий файл.
# ------------------------------------------------------------------
for workflow in "${workflows[@]}"; do
    while IFS= read -r call; do
        [ -z "$call" ] && continue
        if [ ! -f "$call" ]; then
            report "$workflow" "вызов несуществующего скрипта: $call"
            note 'Скрипт переименовали или удалили, а шаг остался.'
        fi
    done < <(calls_in "$workflow")
done

# ------------------------------------------------------------------
printf '\n'
if [ "$VIOLATIONS" -gt 0 ]; then
    printf 'Расхождений: %d. Обвязка и скрипты разъехались.\n' "$VIOLATIONS"
    note 'Проверка, которую перестали запускать, хуже отсутствующей.'
    exit 1
fi

printf 'Обвязка сходится: каждая проверка подключена.\n'
exit 0
