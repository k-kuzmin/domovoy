#!/usr/bin/env bash
#
# Домовой — граница команд Bash для субагента шага.
#
# БЕЗ ОБВЯЗКИ: вызывается хуком PreToolUse из определений .claude/agents/,
# а не шагом workflow. Сценарии скрипта в CI запускаются — сам он нет.
#
# ЗАЧЕМ
#
# В агентском цикле набор команд задан на шаг: `agent-implement.yml` выдаёт
# `dotnet build`, `test`, `format`, `git` и `gh`, но не `dotnet ef` —
# миграции лежат в защищённых путях. Локально такого рычага не было: поле
# `tools` в определении субагента перечисляет инструменты, а не команды
# (скобки поддержаны только у `Agent(...)`, поля `permissions` во
# frontmatter нет). Выдать субагенту `Bash` значило выдать его целиком.
#
# Этот скрипт закрывает разрыв. Определение шага перечисляет свои команды
# аргументами хука, хук получает вызов до исполнения и отвечает отказом,
# если команда в список не попала.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Команда разбирается на части по `&&`, `||`, `;`, `|` и переводам
#      строки: разрешена команда — значит разрешена каждая её часть. Иначе
#      `dotnet build && dotnet ef database drop` прошло бы по первому слову.
#   2. Подстановка команд (`$(…)`, обратные кавычки) — отказ: она прячет
#      вторую команду внутри разрешённой.
#   3. Перенаправление вывода (`>`, `>>`) — отказ: читающему шагу это канал
#      записи в обход отсутствующих Edit и Write.
#   4. Фоновый запуск (`&`) — отказ: результат такой команды не виден ни
#      шагу, ни хуку.
#   5. Перенаправление ввода (`<`) — отказ: подстановка процесса `<(…)`
#      запускает команду мимо списка разрешённого.
#   6. Пустой список разрешённого — отказ. Шаг, забывший перечислить свои
#      команды, не получает Bash целиком по умолчанию.
#   6а. Слово, которое соберёт оболочка, — отказ (ревью #128): обратный слеш
#      вне кавычек перед буквой, цифрой, `_`, `-`, `=` или переводом строки;
#      слеш перед переводом строки и в двойных кавычках; подстановка
#      параметра (`$x`, `${…}`, `$@`, `$[…]`) вне одиночных кавычек; ANSI- и
#      локализуемые кавычки (`$'…'`, `$"…"`); фигурные скобки с запятой или
#      `..` вне кавычек. Проверки 7 и 8 читают текст команды, а не результат
#      её разбора в bash: `--j\q`, `--j${x:-q}`, `$'--jq'` и `--{jq,x}` bash
#      соберёт в `--jq`, а проверка узнать не могла. Отказ ставится по
#      признаку сборки, а не по угаданному результату — угадывать значило бы
#      исполнять оболочку. `$` и `\` в одиночных кавычках, `$` перед
#      закрывающей двойной кавычкой, `\` перед знаком препинания проходят.
#   7. Поимённо запрещённые флаги — отдельно от списка команд, потому что
#      стоят не в начале строки:
#
#        --no-verify и его короткий синоним -n у `git commit` — выключают
#            pre-commit с gitleaks;
#        --force, --force-with-lease, -f у `git push` — перезапись истории;
#        --output у `git` и `gh` — превращает чтение в запись в файл;
#        --add-label, --remove-label у `gh` — шаг снял бы себе гейт;
#        --label, -l и его сцепки (`-dl`, `-lметка`) — только у подкоманд
#            `gh pr create`, `gh issue create`, `gh pr edit`,
#            `gh issue edit`: тот же гейт, снятый в момент создания.
#            `gh pr create --label agent/allow-protected` не правит метки,
#            а рождает PR уже с ними. Область узкая намеренно — `gh pr
#            comment` пишет прозу, и отчёт о самом этом запрете содержит
#            литерал `--label`.
#
#      Проверяются они по словам нормализованной части: кавычки сняты,
#      табуляции приведены к пробелам, значение после `=` отброшено. Учтены
#      однозначные сокращения длинных опций — git принимает `--no-veri`
#      наравне с полным написанием.
#   8. Аргументы `gh` (#119) — у каждой части, начинающейся с `gh `, по тем
#      же нормализованным словам:
#
#        указатель репозитория — каждый `--repo X`, `--repo=X` и короткое
#            слово с буквой R в любой позиции сцепки (`-R X`, `-RX`, `-R=X`,
#            `-cR X`) — только со своим слагом. Каждый, а не первый: у gh
#            повторный указатель переопределяет пришпиленный;
#        адрес GitHub — слово с хостом github.com или *.github.com в любом
#            написании (регистр, `www.`, порт, userinfo, без схемы,
#            git@github.com:o/r) — только со своим слагом в первых двух
#            сегментах пути, сегмент сравнивается целиком;
#        выражение над ответом — `--jq`, `--template` и их сокращения, `-q`
#            и `-t` в короткой сцепке до буквы R — отказ всегда;
#        `gh search` — только со своим `--repo`; `--owner` и квалификаторы
#            repo:, org:, user:, owner: в запросе — отказ.
#
#      Свой слаг выводится из `git -C "$CLAUDE_PROJECT_DIR" remote get-url
#      origin` (https, ssh, scp-форма; хост только github.com) и сравнивается
#      без учёта регистра — GitHub его не различает. Слаг не выведен — отказ
#      всему, что его требует; голые команды проходят.
#
# ПОЧЕМУ РАЗБОР gh ЖИВЁТ ЗДЕСЬ, А НЕ В СПИСКАХ ШАГОВ
#
# Решение владельца в #119. Пришпилить `--repo <слаг>` в списке каждого
# определения значило бы разнести слаг по восьми файлам, а префикс всё равно
# не отбивал бы второй указатель после себя и выражение над ответом. Здесь
# знание в одном месте и выведено из origin, а не переписано руками. Выражение
# над ответом отбивается всегда, потому что `--jq` исполняется целиком и
# читает окружение процесса, где живут токены: отбор, который шагу нужен,
# переезжает в поимённый сценарий (`scripts/owner-comments.sh`). Таблицы
# флагов gh со значением нет намеренно — копия разъехалась бы с версией gh;
# поэтому буква в короткой сцепке означает отказ, и лишний отказ (законный
# `-t` как `--title`) принят.
#
# ЧЕГО ЭТА ГРАНИЦА НЕ ДЕЛАЕТ
#
# Она не разбирает аргументы целиком. Ключи разрешённых команд, кроме
# перечисленных выше, не проверяются: `dotnet build /p:...`, `grep -f`,
# `gh api` с произвольным путём остаются на дисциплине шага — ровно как в
# цикле, где `--allowedTools` задаёт команду, а не её ключи. Отсюда правило
# при правке списков: команда, у которой есть флаг записи или исполнения,
# читающему шагу не выдаётся вовсе. Так из списков ушли `sed`, `git diff` и
# `git log`.
#
# Разбор gh — только в локальном режиме. Цикл (`--allowedTools` в
# `.github/workflows/agent-*.yml`) этот хук не вызывает, и там `--jq` и чужой
# `--repo` по-прежнему проходят. Адрес — #129.
#
# Инлайн-тело (`--body '…'`, `--title '…'`) разбирается по словам наравне с
# флагами: литерал `-t`, `--jq` или адрес чужого репозитория в прозе получит
# отказ. Тело с такими словами передаётся через `--body-file`.
#
# Нормализация по-прежнему снимает кавычки, но оболочку не исполняет. Слово,
# собранное слешем, подстановкой, ANSI-кавычками или скобками, закрыто
# отказом по признаку (пункт 6а). Открытой остаётся подстановка путей:
# `--no-verif[y]`, `*verify` bash раскроет в имя файла, если файл с именем
# флага уже лежит в каталоге. Отказ на `*`, `?`, `[` уронил бы обычные
# `grep -rn x src/*`, а для обхода нужен заранее созданный файл — адреса у
# этого пока нет.
#
# РАЗБОР СМОТРИТ НА КАВЫЧКИ
#
# Обратный слеш вне кавычек перед знаком препинания экранирует следующий
# символ — как в оболочке. Без этого `\'` открывал в разборе кавычку, которой
# для bash нет, и всё после неё считалось текстом: обход на один символ. Слеш
# перед буквой вне кавычек и ANSI-кавычки `$'\''` получают отказ (пункт 6а)
# ещё до того, как разбор успел бы ошибиться с кавычками.
#
# Наивная замена разделителей ломается на первом же сообщении коммита:
# `git commit -m "убрать X; добавить Y"` содержит точку с запятой, а
# `git commit -m "было > стало"` — знак перенаправления. Оба внутри кавычек
# и оба ничего не запускают. Поэтому строка проходится посимвольно с учётом
# одиночных и двойных кавычек: разделителем считается только то, что лежит
# вне них. Иначе запрет пришлось бы обходить, а обходят его каждый день.
#
# ОТКАЗ, А НЕ ПРОПУСК
#
# Всё, чего скрипт не понял, — отказ: нет `jq`, нет команды в JSON, пустой
# список, незакрытая кавычка. Хук границ, уступающий дорогу при собственной
# поломке, — это видимость границы: она держится до первой неполадки и
# молчит о том, что перестала держать.
#
# Отсюда единственное исключение: если событие пришло не про `Bash`, скрипт
# молчит и уступает. Это не поломка, а не его дело.
#
# КАК ЗАПУСКАТЬ
#
# Не руками. Из определения шага:
#
#   hooks:
#     PreToolUse:
#       - matcher: Bash
#         hooks:
#           - type: command
#             command: >-
#               bash "$CLAUDE_PROJECT_DIR/scripts/step-bash-allow.sh"
#               'dotnet build' 'git status'
#
# Вызов руками — только через сценарии: bash scripts/step-bash-allow.test.sh
#
# Код возврата всегда 0: решение передаётся полем permissionDecision, как
# описано в контракте PreToolUse. Код 2 тоже блокирует вызов, но забирает
# причину отказа в stderr, а её должен прочитать субагент.
#
set -uo pipefail

# Причина отказа уходит субагенту, поэтому пишется словами, а не кодом.
#
# Собирается она через jq, а не printf: в причину подставляется команда, а в
# команде может быть что угодно. Ручное экранирование трёх символов давало
# невалидный JSON на первой же табуляции — а отказ, который потребитель не
# может разобрать, читается как «решения нет», то есть как разрешение.
deny() {
    reason="$1"
    # Управляющие символы вырезаются до сборки: в JSON их нельзя внести
    # дословно, а показывать их в причине незачем.
    reason="${reason//[[:cntrl:]]/ }"

    if command -v jq >/dev/null 2>&1; then
        jq -n --arg reason "$reason" \
            '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$reason}}'
        exit 0
    fi

    # Без jq остаётся ручная сборка, и попадает сюда ровно одна причина — та,
    # что jq и не найден. Её текст свой, без кавычек и обратных слешей.
    reason="${reason//\\/\\\\}"
    reason="${reason//\"/\\\"}"
    printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"%s"}}\n' \
        "$reason"
    exit 0
}

# Слово — это запрещённый флаг или его однозначное сокращение.
#
# Сокращения приходится учитывать, потому что git их принимает:
# `git commit --no-veri` выключает хуки так же, как полное написание.
# Сокращением считается начало флага длиной от четырёх символов — короче
# git и сам отвергнет как неоднозначное, а `-f` разбирается отдельно.
is_flag() {
    # local обязателен: без него функция затирает word и flag вызывающего,
    # и вся проверка после первого вызова сравнивает не то, что читает.
    local word="$1"
    local flag="$2"

    [ "$word" = "$flag" ] && return 0

    if [ "${#word}" -ge 4 ] && [ "${flag#"$word"}" != "$flag" ]; then
        return 0
    fi

    return 1
}

# Слово, которое соберёт оболочка, поимённая проверка не узнаёт: она читает
# текст команды, а не результат её разбора в bash. Угадывать результат значило
# бы исполнять оболочку, поэтому отказ ставится по самому признаку сборки.
deny_assembled() {
    deny "Слово в команде собирает оболочка: «$COMMAND». Граница сверяет флаги по тексту команды и оболочку не исполняет, а обратный слеш вне кавычек, перенос строки через слеш, подстановка параметра (\$x, \${…}, \$@), ANSI- и локализуемые кавычки (\$'…', \$\"…\") и фигурные скобки с запятой соберут слово, которого проверка не видит. Пиши значение буквально; \$ и \\ в регулярке — внутри одиночных кавычек."
}

# Молчание = решения нет, дальше работает обычный порядок разрешений.
allow_silently() {
    exit 0
}

# ------------------------------------------------------------------
# Разбор аргументов gh (#119). Четыре ветки — четыре функции, каждая со
# своей точкой выключения: указатель репозитория, адрес github.com,
# выражение над ответом, поиск.
# ------------------------------------------------------------------

# Свой репозиторий выводится из origin, а не записывается в скрипт: знание
# живёт в одном месте, и в форке граница сверяет с форком. Вывод ленивый —
# голый `gh issue view 1` git не зовёт вовсе.
OWN_SLUG=''
SLUG_RESOLVED=0

resolve_own_slug() {
    [ "$SLUG_RESOLVED" -eq 1 ] && return 0
    SLUG_RESOLVED=1

    # Сравнение и классы символов — в локали C: слаг GitHub — ASCII, а
    # диапазоны в регулярке не должны зависеть от локали машины.
    local LC_ALL=C
    local url
    url="$(git -C "${CLAUDE_PROJECT_DIR:-$PWD}" remote get-url origin 2>/dev/null)" || url=''
    url="${url,,}"
    url="${url%/}"
    url="${url%.git}"

    # Три формы origin: https://github.com/o/r, ssh://git@github.com/o/r и
    # git@github.com:o/r. Хост — ровно github.com: origin на другом хосте
    # слага не даёт, и всё, что требует слага, получает отказ.
    local re='^((https?|ssh)://([^/@]+@)?github\.com(:[0-9]+)?/|([^/@:]+@)?github\.com:)([a-z0-9._-]+)/([a-z0-9._-]+)$'
    if [[ "$url" =~ $re ]]; then
        OWN_SLUG="${BASH_REMATCH[6]}/${BASH_REMATCH[7]}"
    fi
}

# Слаг не выведен — сломанный хук не пропускает. Причина называет remote:
# чинить нужно его, а не список разрешённого.
require_own_slug() {
    resolve_own_slug
    if [ -z "$OWN_SLUG" ]; then
        deny "Свой репозиторий не определён — слаг не выведен из origin каталога ${CLAUDE_PROJECT_DIR:-$PWD}, а команда его требует: «$1». Указатель репозитория, адрес github.com и gh search проверяются против origin на github.com; чинить нужно remote, а не список."
    fi
}

# GitHub не различает регистр owner/repo: отказ своему репозиторию в другом
# регистре ничего не защищал бы.
is_own_slug() {
    local LC_ALL=C
    local value="${1,,}"
    [ -n "$OWN_SLUG" ] && [ "$value" = "$OWN_SLUG" ]
}

# Ветка «указатель репозитория». Слово — `--repo` (и его сокращение), либо
# короткое слово с буквой R в любой позиции сцепки: `-R`, `-RX`, `-R=X`,
# `-cR X`, `-cRX`. Значение — остаток после R без ведущего `=` или, если он
# пуст, следующее слово. Таблицы флагов со значением здесь нет намеренно: она
# стала бы копией, которая разъедется с версией gh.
gh_repo_pointer() {
    REPO_VALUE=''
    REPO_TAKES_NEXT=0
    if is_flag "$2" '--repo'; then
        case "$1" in
            *=*) REPO_VALUE="${1#*=}" ;;
            *) REPO_TAKES_NEXT=1 ;;
        esac
        return 0
    fi
    # Шаблон в два шага, как у -l: `-[!-]*R*` не поймал бы голое `-R` —
    # класс [!-] съедает саму R.
    case "$1" in
        -[!-]*)
            case "$1" in
                *R*)
                    local body="${1#-}"
                    REPO_VALUE="${body#*R}"
                    REPO_VALUE="${REPO_VALUE#=}"
                    [ -z "$REPO_VALUE" ] && REPO_TAKES_NEXT=1
                    return 0
                    ;;
            esac
            ;;
    esac
    return 1
}

gh_repo_value_check() {
    require_own_slug "$2"
    if ! is_own_slug "$1"; then
        deny "Указатель репозитория у gh — только свой ($OWN_SLUG): «$2». Каждый --repo и -R сверяется со слагом из origin, и повторный тоже: у gh последний переопределяет пришпиленный."
    fi
}

# Слово — адрес GitHub: необязательная схема в любом регистре, необязательный
# userinfo, хост github.com или *.github.com, необязательный порт, затем `/`.
# Сюда попадают и https://WWW.GitHub.com/…, и https://github.com:443/…, и форма
# без схемы, и git@github.com:o/r. Первые два сегмента пути — в ADDR_SLUG.
github_address_slug() {
    local LC_ALL=C
    local word="${1,,}"
    local path=''
    local re='^([^/:@]+://)?([^/@]*@)?([^/@:]*\.)?github\.com(:[0-9]*)?/(.*)$'
    local re_scp='^([^/@]*@)?([^/@:]*\.)?github\.com:(.+)$'

    if [[ "$word" =~ $re ]]; then
        path="${BASH_REMATCH[5]}"
    elif [[ "$word" =~ $re_scp ]]; then
        path="${BASH_REMATCH[3]}"
    else
        return 1
    fi

    path="${path%%[?#]*}"
    local owner="${path%%/*}"
    local rest=''
    [ "$owner" != "$path" ] && rest="${path#*/}"
    local repo="${rest%%/*}"
    repo="${repo%.git}"
    ADDR_SLUG=''
    if [ -n "$owner" ] && [ -n "$repo" ]; then
        ADDR_SLUG="$owner/$repo"
    fi
    return 0
}

# Ветка «адрес github.com». Адреса других хостов не трогаются: gh ходит только
# на GitHub. Сегмент сравнивается целиком, поэтому `<слаг>-злой` — отказ.
gh_address_check() {
    github_address_slug "$1" || return 0
    require_own_slug "$2"
    if [ -z "$ADDR_SLUG" ] || ! is_own_slug "$ADDR_SLUG"; then
        deny "Адрес github.com у gh — только своего репозитория ($OWN_SLUG): «$2». Адрес в тексте тела передавай через --body-file."
    fi
}

# Ветка «выражение над ответом». `--jq` исполняется целиком и читает окружение
# процесса, где живут токены; `--template` — то же через Go-шаблон. Короткие
# `-q` и `-t` ловятся в сцепке приёмом, что у -l: буква до R — отказ; буквы
# после R — значение указателя, и на q и t они не проверяются. Лишний отказ
# законному `-t` (`--title`) принят: длинная форма проходит.
gh_expression_check() {
    if is_flag "$2" '--jq' || is_flag "$2" '--template'; then
        deny "Выражение над ответом запрещено у gh: «$3». --jq и --template исполняются целиком и видят окружение процесса; бери --json и отбирай готовый вывод. Литерал флага в тексте тела — через --body-file."
    fi
    case "$1" in
        -[!-]*)
            local body="${1#-}"
            local head="${body%%R*}"
            head="${head%%=*}"
            case "$head" in
                *q* | *t*)
                    deny "Короткие -q и -t запрещены у gh: «$3». Это --jq и --template слитно; заголовок пиши длинной формой --title, текст с дефисами — через --body-file."
                    ;;
            esac
            ;;
    esac
}

# Ветка «поиск», по словам. `--owner` и квалификаторы repo:, org:, user:,
# owner: в запросе расширяют область поиска на чужие репозитории, даже при
# своём --repo.
gh_search_word_check() {
    if is_flag "$2" '--owner'; then
        deny "Флаг --owner запрещён у gh search: «$3». Поиск идёт только по своему репозиторию через --repo."
    fi
    local LC_ALL=C
    local lowered="${1,,}"
    case "$lowered" in
        repo:* | org:* | user:* | owner:*)
            deny "Квалификатор области в запросе gh search запрещён: «$3». repo:, org:, user: и owner: расширяют поиск на чужие репозитории; область задаёт --repo."
            ;;
    esac
}

# Ветка «поиск», по части целиком: у поиска нет репозитория по умолчанию,
# поэтому без своего --repo он идёт по всему GitHub.
gh_search_scope_check() {
    if [ "$2" -eq 0 ]; then
        require_own_slug "$1"
        deny "gh search без --repo своего репозитория ($OWN_SLUG) запрещён: «$1». У поиска нет репозитория по умолчанию, и без указателя он идёт по всему GitHub."
    fi
}

# Проход по словам части, начинающейся с `gh `. Слова — из нормализованной
# части, по индексу: значение указателя стоит следующим словом.
check_gh_part() {
    local part="$1"
    local -a words
    read -r -a words <<< "$2"
    local count="${#words[@]}"
    local index=0
    local word flag
    local is_search=0
    local own_pointer=0

    case "$part" in
        'gh search'*) is_search=1 ;;
    esac

    while [ "$index" -lt "$count" ]; do
        word="${words[index]}"
        flag="${word%%=*}"

        gh_expression_check "$word" "$flag" "$part"

        if gh_repo_pointer "$word" "$flag"; then
            if [ "$REPO_TAKES_NEXT" -eq 1 ]; then
                index=$((index + 1))
                REPO_VALUE="${words[index]:-}"
            fi
            gh_repo_value_check "$REPO_VALUE" "$part"
            own_pointer=1
            index=$((index + 1))
            continue
        fi

        gh_address_check "$word" "$part"

        if [ "$is_search" -eq 1 ]; then
            gh_search_word_check "$word" "$flag" "$part"
        fi

        index=$((index + 1))
    done

    if [ "$is_search" -eq 1 ]; then
        gh_search_scope_check "$part" "$own_pointer"
    fi
}

# Вход читается встроенным read, а не через cat: при поломке окружения
# (пустой PATH) внешних команд может не быть вовсе, а отказать хук обязан и
# в этом случае.
INPUT=''
read -r -d '' INPUT || true

if ! command -v jq >/dev/null 2>&1; then
    deny "Граница команд шага не проверена: не найден jq. Установи jq или запусти шаг без Bash — пропустить непроверенную команду хук не может."
fi

TOOL="$(printf '%s' "$INPUT" | jq -r '.tool_name // empty' 2>/dev/null)"

# Не Bash — не наше дело. Матчер в определении и так сужает событие, но
# полагаться на его правку не стоит.
case "$TOOL" in
    Bash) ;;
    '') deny "Граница команд шага не проверена: во входе хука нет tool_name." ;;
    *) allow_silently ;;
esac

COMMAND="$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null)"

if [ -z "$COMMAND" ]; then
    deny "Граница команд шага не проверена: во входе хука нет tool_input.command."
fi

if [ "$#" -eq 0 ]; then
    deny "Шаг не перечислил разрешённые команды, поэтому Bash ему не выдан. Список задаётся аргументами хука в определении шага."
fi

# ------------------------------------------------------------------
# Разбор на части с учётом кавычек.
# ------------------------------------------------------------------
parts=()
current=''
in_single=0
in_double=0
position=0
length="${#COMMAND}"

flush_part() {
    parts+=("$current")
    current=''
}

while [ "$position" -lt "$length" ]; do
    char="${COMMAND:position:1}"
    next="${COMMAND:$((position + 1)):1}"

    # Внутри одиночных кавычек не работает ничего: ни подстановка, ни
    # разделители. Текст переносится как есть до закрывающей кавычки.
    if [ "$in_single" -eq 1 ]; then
        [ "$char" = "'" ] && in_single=0
        current="$current$char"
        position=$((position + 1))
        continue
    fi

    if [ "$in_double" -eq 1 ]; then
        case "$char" in
            '\')
                # Слеш перед переводом строки bash вырезает вместе с ним и
                # внутри двойных кавычек: `"--no-veri\<перевод>fy"` — целый
                # флаг, а разбор по словам видит две половины. `\r` — перевод
                # строки от jq на Windows.
                case "$next" in
                    $'\n' | $'\r') deny_assembled ;;
                esac
                # Экранированный символ переносится парой: иначе \" закрыл
                # бы кавычку в разборе, но не в оболочке.
                current="$current$char$next"
                position=$((position + 2))
                continue
                ;;
            '`')
                deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
                ;;
            '$')
                if [ "$next" = '(' ]; then
                    deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
                fi
                # Подстановка параметра работает и в двойных кавычках. `$`
                # перед закрывающей кавычкой, пробелом или `|` — буквальный:
                # это конец регулярки, а не подстановка.
                case "$next" in
                    '{' | '[' | [A-Za-z0-9_] | '@' | '*' | '#' | '?' | '$' | '!' | '-')
                        deny_assembled
                        ;;
                esac
                ;;
            '"')
                in_double=0
                ;;
        esac
        current="$current$char"
        position=$((position + 1))
        continue
    fi

    case "$char" in
        '\')
            # Вне кавычек обратный слеш экранирует следующий символ, а
            # оболочка потом его снимает: `--j\q` доходит до gh как `--jq`,
            # `--no-veri\<перевод>fy` — как `--no-verify`. Проверка по словам
            # видит слеш и флага не узнаёт. Отказ — на слеш перед символом,
            # из которого складывается имя флага (буква, цифра, `_`, `-`,
            # `=`), и перед переводом строки. `\r` — потому что jq на Windows
            # отдаёт перевод строки парой CR LF.
            case "$next" in
                [A-Za-z0-9_=-] | $'\n' | $'\r') deny_assembled ;;
            esac
            # Перед знаком препинания слеш флага не собирает и переносится
            # парой: `\'` — это литеральная кавычка, и разбор продолжается
            # вне кавычек. Без этого `head x \' ; чужая команда ; echo \'`
            # выглядел закавыченным и проходил целиком — проверки
            # разделителей, подстановки и перенаправления терялись разом.
            current="$current$char$next"
            position=$((position + 2))
            continue
            ;;
        "'")
            in_single=1
            current="$current$char"
            ;;
        '"')
            in_double=1
            current="$current$char"
            ;;
        '`')
            deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
            ;;
        '$')
            if [ "$next" = '(' ]; then
                deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
            fi
            # Вне кавычек к подстановке параметра добавляются ANSI- и
            # локализуемые кавычки. `$'…'` к тому же ломает сам разбор: в
            # `$'\''` bash видит одну литеральную кавычку, а разбор — открытую
            # строку, и следующие команды склеивались в разрешённую часть.
            case "$next" in
                "'" | '"' | '{' | '[' | [A-Za-z0-9_] | '@' | '*' | '#' | '?' | '$' | '!' | '-')
                    deny_assembled
                    ;;
            esac
            current="$current$char"
            ;;
        '{')
            # Фигурные скобки вне кавычек с запятой или `..` внутри bash
            # раскрывает в несколько слов: `--{jq,x}` — это `--jq --x`. Без
            # пробела до закрывающей скобки — это она; `{owner}` без запятой
            # оболочка не трогает.
            rest="${COMMAND:position}"
            inner="${rest%%\}*}"
            if [ "$inner" != "$rest" ]; then
                case "$inner" in
                    *[[:space:]]*) ;;
                    *,* | *..*) deny_assembled ;;
                esac
            fi
            current="$current$char"
            ;;
        '>')
            deny "Перенаправление вывода запрещено на шаге: «$COMMAND». Это канал записи в обход набора инструментов."
            ;;
        '<')
            # Подстановка процесса `<(…)` запускает команду, которую список
            # разрешённого не видит: «grep error <(dotnet ef …)» прошло бы по
            # первому слову. Отсюда запрет на `<` целиком — чтение файла
            # обходится инструментом Read.
            deny "Перенаправление ввода запрещено на шаге: «$COMMAND». Внутри «<(…)» запускается команда, которой в списке разрешённого нет, а файл читается инструментом Read."
            ;;
        '&')
            if [ "$next" = '&' ]; then
                flush_part
                position=$((position + 2))
                continue
            fi
            deny "Фоновый запуск запрещён на шаге: «$COMMAND». Результат такой команды не виден ни шагу, ни этой проверке."
            ;;
        '|')
            flush_part
            if [ "$next" = '|' ]; then
                position=$((position + 2))
                continue
            fi
            ;;
        ';' | $'\n')
            flush_part
            ;;
        *)
            current="$current$char"
            ;;
    esac

    position=$((position + 1))
done

if [ "$in_single" -eq 1 ] || [ "$in_double" -eq 1 ]; then
    deny "Незакрытая кавычка в команде: «$COMMAND». Разобрать её на части нельзя, а пропустить неразобранное хук не может."
fi

flush_part

# ------------------------------------------------------------------
# Сверка частей со списком разрешённого.
# ------------------------------------------------------------------
for part in "${parts[@]}"; do
    # Пробелы по краям убираются: «git status && git diff» даёт часть
    # « git diff», и без этого она не совпала бы ни с чем.
    part="${part#"${part%%[![:space:]]*}"}"
    part="${part%"${part##*[![:space:]]}"}"
    [ -z "$part" ] && continue

    # Флаги, превращающие разрешённую команду в запись, в исполнение или в
    # обход хуков. Список команд смотрит на начало строки, а флаг стоит где
    # угодно, — поэтому проверка отдельная.
    #
    # Проверяется она по словам нормализованной части, а не поиском подстроки
    # в сырой: оболочка снимет кавычки, и `git commit --no-veri"fy"` дойдёт
    # до git целым флагом. Плюс git принимает однозначные сокращения длинных
    # опций, то есть `--no-veri` выключает хуки не хуже полного написания.
    normalized="${part//\'/}"
    normalized="${normalized//\"/}"
    normalized="${normalized//$'\t'/ }"

    for word in $normalized; do
        # Значение отрезается: `--output=/tmp/x` — тот же флаг.
        flag="${word%%=*}"

        if is_flag "$flag" '--no-verify'; then
            deny "Флаг --no-verify запрещён: «$part». Он выключает pre-commit с gitleaks, и запрет на него записан в .claude/CLAUDE.md."
        fi

        case "$part" in
            'git commit'*)
                # Короткий синоним и его сцепки: `-n`, `-nm`.
                case "$flag" in
                    -[!-]*)
                        case "$flag" in
                            *n*) deny "Флаг -n запрещён у git commit: «$part». Это тот же --no-verify, только короче." ;;
                        esac
                        ;;
                esac
                ;;
            'git push'*)
                if is_flag "$flag" '--force' || is_flag "$flag" '--force-with-lease' \
                    || [ "$flag" = '-f' ]; then
                    deny "Насильный пуш запрещён на шаге: «$part». Перезапись истории ветки, которую уже видели CI и ревью, — решение человека, а не шага."
                fi
                ;;
        esac

        case "$part" in
            'git '*|'gh '*)
                if is_flag "$flag" '--output'; then
                    deny "Флаг --output запрещён у git и gh: «$part». Он делает из читающей команды запись в файл, минуя набор инструментов."
                fi
                if [ "$flag" = '--add-label' ] || [ "$flag" = '--remove-label' ]; then
                    deny "Правка меток запрещена на шаге: «$part». Метки agent/allow-* — разрешения человека, и снимать их себе шаг не может."
                fi
                ;;
        esac

        # Назначение метки при создании — та же дырка, что --add-label, только
        # через другой флаг: `gh pr create --label agent/allow-protected`
        # ничего не «правит», а открывает PR уже с разрешением.
        #
        # Область — только подкоманды, которые метку действительно назначают.
        # Шире нельзя: `gh pr comment` пишет прозу, и отчёт о самом этом
        # запрете содержит литерал `--label`; на широкой области шаг не смог бы
        # рассказать о границе, которой подчиняется.
        case "$part" in
            'gh pr create'*|'gh issue create'*|'gh pr edit'*|'gh issue edit'*)
                if is_flag "$flag" '--label'; then
                    deny "Назначение меток запрещено на шаге: «$part». Открыть PR сразу с agent/allow-* значит снять себе гейт целостности в момент создания — разрешение ставит человек. Упомянуть флаг в тексте можно через --body-file."
                fi
                # Короткий синоним и его сцепки: gh разбирает флаги через
                # pflag, а он принимает и `-dl метка` (буква d — булев
                # --draft), и приклеенное значение `-lметка`. Точное сравнение
                # с `-l` пропускало оба написания — тот же приём, что у -n
                # выше, ловит все три.
                case "$flag" in
                    -[!-]*)
                        case "$flag" in
                            *l*) deny "Короткий флаг -l запрещён на шаге: «$part». Это то же назначение метки, только слитно; разрешение ставит человек." ;;
                        esac
                        ;;
                esac
                ;;
        esac
    done

    # Разбор аргументов gh — после поимённых флагов: у них свои причины
    # отказа, и они называются первыми.
    case "$part" in
        'gh '*) check_gh_part "$part" "$normalized" ;;
    esac

    matched=0
    for allowed in "$@"; do
        # Совпадением считается начало строки: «dotnet build» разрешает
        # «dotnet build --no-restore -c Release», но не «dotnet ef».
        if [ "$part" = "$allowed" ] || [ "${part#"$allowed" }" != "$part" ]; then
            matched=1
            break
        fi
    done

    if [ "$matched" -eq 0 ]; then
        deny "Команда «$part» не входит в список разрешённого на этом шаге. Разрешено: $*."
    fi
done

allow_silently
