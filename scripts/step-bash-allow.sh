#!/usr/bin/env bash
#
# Домовой — граница команд Bash для субагента шага.
#
# БЕЗ ОБВЯЗКИ: вызывается хуком PreToolUse из определений .claude/agents/,
# а не шагом workflow. Сценарии скрипта в CI запускаются — сам он нет.
#
# ЗАЧЕМ
#
# В агентском цикле набор команд задан на шаг: `agent-implement.yml` выдаёт
# `dotnet build`, `test`, `format`, `git` и `gh`, но не `dotnet ef` —
# миграции лежат в защищённых путях. Локально такого рычага не было: поле
# `tools` в определении субагента перечисляет инструменты, а не команды
# (скобки поддержаны только у `Agent(...)`, поля `permissions` во
# frontmatter нет). Выдать субагенту `Bash` значило выдать его целиком.
#
# Этот скрипт закрывает разрыв. Определение шага перечисляет свои команды
# аргументами хука, хук получает вызов до исполнения и отвечает отказом,
# если команда в список не попала.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Команда разбирается на части по `&&`, `||`, `;`, `|` и переводам
#      строки: разрешена команда — значит разрешена каждая её часть. Иначе
#      `dotnet build && dotnet ef database drop` прошло бы по первому слову.
#   2. Подстановка команд (`$(…)`, обратные кавычки) — отказ: она прячет
#      вторую команду внутри разрешённой.
#   3. Перенаправление вывода (`>`, `>>`) — отказ: читающему шагу это канал
#      записи в обход отсутствующих Edit и Write.
#   4. Фоновый запуск (`&`) — отказ: результат такой команды не виден ни
#      шагу, ни хуку.
#   5. Перенаправление ввода (`<`) — отказ: подстановка процесса `<(…)`
#      запускает команду мимо списка разрешённого.
#   6. Пустой список разрешённого — отказ. Шаг, забывший перечислить свои
#      команды, не получает Bash целиком по умолчанию.
#   7. Поимённо запрещённые флаги — отдельно от списка команд, потому что
#      стоят не в начале строки:
#
#        --no-verify и его короткий синоним -n у `git commit` — выключают
#            pre-commit с gitleaks;
#        --force, --force-with-lease, -f у `git push` — перезапись истории;
#        --output у `git` и `gh` — превращает чтение в запись в файл;
#        --add-label, --remove-label у `gh` — шаг снял бы себе гейт;
#        --label и -l у `gh` — тот же гейт, снятый в момент создания:
#            `gh pr create --label agent/allow-protected` не правит метки,
#            а рождает PR уже с ними.
#
#      Проверяются они по словам нормализованной части: кавычки сняты,
#      табуляции приведены к пробелам, значение после `=` отброшено. Учтены
#      однозначные сокращения длинных опций — git принимает `--no-veri`
#      наравне с полным написанием.
#
# ЧЕГО ЭТА ГРАНИЦА НЕ ДЕЛАЕТ
#
# Она не разбирает аргументы целиком. Ключи разрешённых команд, кроме
# перечисленных выше, не проверяются: `dotnet build /p:...`, `grep -f`,
# `gh api` с произвольным путём остаются на дисциплине шага — ровно как в
# цикле, где `--allowedTools` задаёт команду, а не её ключи. Отсюда правило
# при правке списков: команда, у которой есть флаг записи или исполнения,
# читающему шагу не выдаётся вовсе. Так из списков ушли `sed`, `git diff` и
# `git log`.
#
# РАЗБОР СМОТРИТ НА КАВЫЧКИ
#
# Обратный слеш вне кавычек экранирует следующий символ — как в оболочке.
# Без этого `\'` открывал в разборе кавычку, которой для bash нет, и всё
# после неё считалось текстом: обход на один символ.
#
# Наивная замена разделителей ломается на первом же сообщении коммита:
# `git commit -m "убрать X; добавить Y"` содержит точку с запятой, а
# `git commit -m "было > стало"` — знак перенаправления. Оба внутри кавычек
# и оба ничего не запускают. Поэтому строка проходится посимвольно с учётом
# одиночных и двойных кавычек: разделителем считается только то, что лежит
# вне них. Иначе запрет пришлось бы обходить, а обходят его каждый день.
#
# ОТКАЗ, А НЕ ПРОПУСК
#
# Всё, чего скрипт не понял, — отказ: нет `jq`, нет команды в JSON, пустой
# список, незакрытая кавычка. Хук границ, уступающий дорогу при собственной
# поломке, — это видимость границы: она держится до первой неполадки и
# молчит о том, что перестала держать.
#
# Отсюда единственное исключение: если событие пришло не про `Bash`, скрипт
# молчит и уступает. Это не поломка, а не его дело.
#
# КАК ЗАПУСКАТЬ
#
# Не руками. Из определения шага:
#
#   hooks:
#     PreToolUse:
#       - matcher: Bash
#         hooks:
#           - type: command
#             command: >-
#               bash "$CLAUDE_PROJECT_DIR/scripts/step-bash-allow.sh"
#               'dotnet build' 'git status'
#
# Вызов руками — только через сценарии: bash scripts/step-bash-allow.test.sh
#
# Код возврата всегда 0: решение передаётся полем permissionDecision, как
# описано в контракте PreToolUse. Код 2 тоже блокирует вызов, но забирает
# причину отказа в stderr, а её должен прочитать субагент.
#
set -uo pipefail

# Причина отказа уходит субагенту, поэтому пишется словами, а не кодом.
#
# Собирается она через jq, а не printf: в причину подставляется команда, а в
# команде может быть что угодно. Ручное экранирование трёх символов давало
# невалидный JSON на первой же табуляции — а отказ, который потребитель не
# может разобрать, читается как «решения нет», то есть как разрешение.
deny() {
    reason="$1"
    # Управляющие символы вырезаются до сборки: в JSON их нельзя внести
    # дословно, а показывать их в причине незачем.
    reason="${reason//[[:cntrl:]]/ }"

    if command -v jq >/dev/null 2>&1; then
        jq -n --arg reason "$reason" \
            '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$reason}}'
        exit 0
    fi

    # Без jq остаётся ручная сборка, и попадает сюда ровно одна причина — та,
    # что jq и не найден. Её текст свой, без кавычек и обратных слешей.
    reason="${reason//\\/\\\\}"
    reason="${reason//\"/\\\"}"
    printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"%s"}}\n' \
        "$reason"
    exit 0
}

# Слово — это запрещённый флаг или его однозначное сокращение.
#
# Сокращения приходится учитывать, потому что git их принимает:
# `git commit --no-veri` выключает хуки так же, как полное написание.
# Сокращением считается начало флага длиной от четырёх символов — короче
# git и сам отвергнет как неоднозначное, а `-f` разбирается отдельно.
is_flag() {
    # local обязателен: без него функция затирает word и flag вызывающего,
    # и вся проверка после первого вызова сравнивает не то, что читает.
    local word="$1"
    local flag="$2"

    [ "$word" = "$flag" ] && return 0

    if [ "${#word}" -ge 4 ] && [ "${flag#"$word"}" != "$flag" ]; then
        return 0
    fi

    return 1
}

# Молчание = решения нет, дальше работает обычный порядок разрешений.
allow_silently() {
    exit 0
}

# Вход читается встроенным read, а не через cat: при поломке окружения
# (пустой PATH) внешних команд может не быть вовсе, а отказать хук обязан и
# в этом случае.
INPUT=''
read -r -d '' INPUT || true

if ! command -v jq >/dev/null 2>&1; then
    deny "Граница команд шага не проверена: не найден jq. Установи jq или запусти шаг без Bash — пропустить непроверенную команду хук не может."
fi

TOOL="$(printf '%s' "$INPUT" | jq -r '.tool_name // empty' 2>/dev/null)"

# Не Bash — не наше дело. Матчер в определении и так сужает событие, но
# полагаться на его правку не стоит.
case "$TOOL" in
    Bash) ;;
    '') deny "Граница команд шага не проверена: во входе хука нет tool_name." ;;
    *) allow_silently ;;
esac

COMMAND="$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null)"

if [ -z "$COMMAND" ]; then
    deny "Граница команд шага не проверена: во входе хука нет tool_input.command."
fi

if [ "$#" -eq 0 ]; then
    deny "Шаг не перечислил разрешённые команды, поэтому Bash ему не выдан. Список задаётся аргументами хука в определении шага."
fi

# ------------------------------------------------------------------
# Разбор на части с учётом кавычек.
# ------------------------------------------------------------------
parts=()
current=''
in_single=0
in_double=0
position=0
length="${#COMMAND}"

flush_part() {
    parts+=("$current")
    current=''
}

while [ "$position" -lt "$length" ]; do
    char="${COMMAND:position:1}"
    next="${COMMAND:$((position + 1)):1}"

    # Внутри одиночных кавычек не работает ничего: ни подстановка, ни
    # разделители. Текст переносится как есть до закрывающей кавычки.
    if [ "$in_single" -eq 1 ]; then
        [ "$char" = "'" ] && in_single=0
        current="$current$char"
        position=$((position + 1))
        continue
    fi

    if [ "$in_double" -eq 1 ]; then
        case "$char" in
            '\')
                # Экранированный символ переносится парой: иначе \" закрыл
                # бы кавычку в разборе, но не в оболочке.
                current="$current$char$next"
                position=$((position + 2))
                continue
                ;;
            '`')
                deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
                ;;
            '$')
                if [ "$next" = '(' ]; then
                    deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
                fi
                ;;
            '"')
                in_double=0
                ;;
        esac
        current="$current$char"
        position=$((position + 1))
        continue
    fi

    case "$char" in
        '\')
            # Вне кавычек обратный слеш экранирует следующий символ: `\'` —
            # это литеральная кавычка, и разбор продолжается вне кавычек.
            # Без этой ветки `head x \' ; чужая команда ; echo \'` выглядел
            # закавыченным и проходил целиком — проверки разделителей,
            # подстановки и перенаправления теряются разом.
            current="$current$char$next"
            position=$((position + 2))
            continue
            ;;
        "'")
            in_single=1
            current="$current$char"
            ;;
        '"')
            in_double=1
            current="$current$char"
            ;;
        '`')
            deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
            ;;
        '$')
            if [ "$next" = '(' ]; then
                deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
            fi
            current="$current$char"
            ;;
        '>')
            deny "Перенаправление вывода запрещено на шаге: «$COMMAND». Это канал записи в обход набора инструментов."
            ;;
        '<')
            # Подстановка процесса `<(…)` запускает команду, которую список
            # разрешённого не видит: «grep error <(dotnet ef …)» прошло бы по
            # первому слову. Отсюда запрет на `<` целиком — чтение файла
            # обходится инструментом Read.
            deny "Перенаправление ввода запрещено на шаге: «$COMMAND». Внутри «<(…)» запускается команда, которой в списке разрешённого нет, а файл читается инструментом Read."
            ;;
        '&')
            if [ "$next" = '&' ]; then
                flush_part
                position=$((position + 2))
                continue
            fi
            deny "Фоновый запуск запрещён на шаге: «$COMMAND». Результат такой команды не виден ни шагу, ни этой проверке."
            ;;
        '|')
            flush_part
            if [ "$next" = '|' ]; then
                position=$((position + 2))
                continue
            fi
            ;;
        ';' | $'\n')
            flush_part
            ;;
        *)
            current="$current$char"
            ;;
    esac

    position=$((position + 1))
done

if [ "$in_single" -eq 1 ] || [ "$in_double" -eq 1 ]; then
    deny "Незакрытая кавычка в команде: «$COMMAND». Разобрать её на части нельзя, а пропустить неразобранное хук не может."
fi

flush_part

# ------------------------------------------------------------------
# Сверка частей со списком разрешённого.
# ------------------------------------------------------------------
for part in "${parts[@]}"; do
    # Пробелы по краям убираются: «git status && git diff» даёт часть
    # « git diff», и без этого она не совпала бы ни с чем.
    part="${part#"${part%%[![:space:]]*}"}"
    part="${part%"${part##*[![:space:]]}"}"
    [ -z "$part" ] && continue

    # Флаги, превращающие разрешённую команду в запись, в исполнение или в
    # обход хуков. Список команд смотрит на начало строки, а флаг стоит где
    # угодно, — поэтому проверка отдельная.
    #
    # Проверяется она по словам нормализованной части, а не поиском подстроки
    # в сырой: оболочка снимет кавычки, и `git commit --no-veri"fy"` дойдёт
    # до git целым флагом. Плюс git принимает однозначные сокращения длинных
    # опций, то есть `--no-veri` выключает хуки не хуже полного написания.
    normalized="${part//\'/}"
    normalized="${normalized//\"/}"
    normalized="${normalized//$'\t'/ }"

    for word in $normalized; do
        # Значение отрезается: `--output=/tmp/x` — тот же флаг.
        flag="${word%%=*}"

        if is_flag "$flag" '--no-verify'; then
            deny "Флаг --no-verify запрещён: «$part». Он выключает pre-commit с gitleaks, и запрет на него записан в .claude/CLAUDE.md."
        fi

        case "$part" in
            'git commit'*)
                # Короткий синоним и его сцепки: `-n`, `-nm`.
                case "$flag" in
                    -[!-]*)
                        case "$flag" in
                            *n*) deny "Флаг -n запрещён у git commit: «$part». Это тот же --no-verify, только короче." ;;
                        esac
                        ;;
                esac
                ;;
            'git push'*)
                if is_flag "$flag" '--force' || is_flag "$flag" '--force-with-lease' \
                    || [ "$flag" = '-f' ]; then
                    deny "Насильный пуш запрещён на шаге: «$part». Перезапись истории ветки, которую уже видели CI и ревью, — решение человека, а не шага."
                fi
                ;;
        esac

        case "$part" in
            'git '*|'gh '*)
                if is_flag "$flag" '--output'; then
                    deny "Флаг --output запрещён у git и gh: «$part». Он делает из читающей команды запись в файл, минуя набор инструментов."
                fi
                if [ "$flag" = '--add-label' ] || [ "$flag" = '--remove-label' ]; then
                    deny "Правка меток запрещена на шаге: «$part». Метки agent/allow-* — разрешения человека, и снимать их себе шаг не может."
                fi
                # Назначение метки при создании — та же дырка, только через
                # другой флаг: `gh pr create --label agent/allow-protected`
                # ничего не «правит», а открывает PR уже с разрешением.
                if is_flag "$flag" '--label' || [ "$flag" = '-l' ]; then
                    deny "Назначение меток запрещено на шаге: «$part». Открыть PR сразу с agent/allow-* значит снять себе гейт целостности в момент создания — разрешение ставит человек."
                fi
                ;;
        esac
    done

    matched=0
    for allowed in "$@"; do
        # Совпадением считается начало строки: «dotnet build» разрешает
        # «dotnet build --no-restore -c Release», но не «dotnet ef».
        if [ "$part" = "$allowed" ] || [ "${part#"$allowed" }" != "$part" ]; then
            matched=1
            break
        fi
    done

    if [ "$matched" -eq 0 ]; then
        deny "Команда «$part» не входит в список разрешённого на этом шаге. Разрешено: $*."
    fi
done

allow_silently
