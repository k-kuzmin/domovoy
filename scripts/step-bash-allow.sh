#!/usr/bin/env bash
#
# Домовой — граница команд Bash для субагента шага.
#
# БЕЗ ОБВЯЗКИ: вызывается хуком PreToolUse из определений .claude/agents/,
# а не шагом workflow. Сценарии скрипта в CI запускаются — сам он нет.
#
# ЗАЧЕМ
#
# В агентском цикле набор команд задан на шаг: `agent-implement.yml` выдаёт
# `dotnet build`, `test`, `format`, `git` и `gh`, но не `dotnet ef` —
# миграции лежат в защищённых путях. Локально такого рычага не было: поле
# `tools` в определении субагента перечисляет инструменты, а не команды
# (скобки поддержаны только у `Agent(...)`, поля `permissions` во
# frontmatter нет). Выдать субагенту `Bash` значило выдать его целиком.
#
# Этот скрипт закрывает разрыв. Определение шага перечисляет свои команды
# аргументами хука, хук получает вызов до исполнения и отвечает отказом,
# если команда в список не попала.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   1. Команда целиком разбирается на части по `&&`, `||`, `;`, `|` и
#      переводам строки: разрешена команда — значит разрешена каждая её
#      часть. Иначе `dotnet build && dotnet ef database drop` прошло бы по
#      первому слову.
#   2. Подстановка команд (`$(…)`, обратные кавычки) запрещена целиком: она
#      прячет вторую команду внутри разрешённой.
#   3. Перенаправление вывода в файл (`>`, `>>`) запрещено: читающему шагу
#      это канал записи в обход отсутствующих Edit и Write.
#   4. Пустой список разрешённого — отказ. Шаг, забывший перечислить свои
#      команды, не получает Bash целиком по умолчанию.
#
# ОТКАЗ, А НЕ ПРОПУСК
#
# Всё, чего скрипт не понял, — отказ: нет `jq`, нет команды в JSON, пустой
# список. Хук границ, уступающий дорогу при собственной поломке, — это
# видимость границы: она держится до первой неполадки и молчит о том, что
# перестала держать.
#
# Отсюда единственное исключение: если событие пришло не про `Bash`, скрипт
# молчит и уступает. Это не поломка, а не его дело.
#
# КАК ЗАПУСКАТЬ
#
# Не руками. Из определения шага:
#
#   hooks:
#     PreToolUse:
#       - matcher: Bash
#         hooks:
#           - type: command
#             command: bash scripts/step-bash-allow.sh 'dotnet build' 'git status'
#
# Вызов руками — только через сценарии: bash scripts/step-bash-allow.test.sh
#
# Код возврата всегда 0: решение передаётся полем permissionDecision, как
# описано в контракте PreToolUse. Код 2 тоже блокирует вызов, но забирает
# причину отказа в stderr, а её должен прочитать субагент.
#
set -uo pipefail

# Причина отказа уходит субагенту, поэтому пишется словами, а не кодом.
deny() {
    # Кавычки в причине ломают JSON — экранируется то, что может встретиться
    # в команде: обратный слеш, двойная кавычка, перевод строки.
    reason="$1"
    reason="${reason//\\/\\\\}"
    reason="${reason//\"/\\\"}"
    reason="${reason//$'\n'/ }"
    printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"%s"}}\n' \
        "$reason"
    exit 0
}

# Молчание = решения нет, дальше работает обычный порядок разрешений.
allow_silently() {
    exit 0
}

# Вход читается встроенным read, а не через cat: при поломке окружения
# (пустой PATH) внешних команд может не быть вовсе, а отказать хук обязан и
# в этом случае.
INPUT=''
read -r -d '' INPUT || true

if ! command -v jq >/dev/null 2>&1; then
    deny "Граница команд шага не проверена: не найден jq. Установи jq или запусти шаг без Bash — пропустить непроверенную команду хук не может."
fi

TOOL="$(printf '%s' "$INPUT" | jq -r '.tool_name // empty' 2>/dev/null)"

# Не Bash — не наше дело. Матчер в определении и так сужает событие, но
# полагаться на его правку не стоит.
case "$TOOL" in
    Bash) ;;
    '') deny "Граница команд шага не проверена: во входе хука нет tool_name." ;;
    *) allow_silently ;;
esac

COMMAND="$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null)"

if [ -z "$COMMAND" ]; then
    deny "Граница команд шага не проверена: во входе хука нет tool_input.command."
fi

if [ "$#" -eq 0 ]; then
    deny "Шаг не перечислил разрешённые команды, поэтому Bash ему не выдан. Список задаётся аргументами хука в определении шага."
fi

case "$COMMAND" in
    *'$('*|*'`'*)
        deny "Подстановка команд запрещена на шаге: «$COMMAND». Внутри неё прячется вторая команда, и список разрешённого её не видит."
        ;;
    *'>'*)
        deny "Перенаправление вывода запрещено на шаге: «$COMMAND». Это канал записи в обход набора инструментов."
        ;;
esac

# Разбор на части. Разделители заменяются переводом строки, дальше каждая
# часть проверяется отдельно: разрешена команда — значит разрешена каждая
# её часть.
PARTS="$COMMAND"
PARTS="${PARTS//&&/$'\n'}"
PARTS="${PARTS//||/$'\n'}"
PARTS="${PARTS//;/$'\n'}"
PARTS="${PARTS//|/$'\n'}"

while IFS= read -r part; do
    # Пробелы по краям убираются: «git status && git diff» даёт часть
    # « git diff», и без этого она не совпала бы ни с чем.
    part="${part#"${part%%[![:space:]]*}"}"
    part="${part%"${part##*[![:space:]]}"}"
    [ -z "$part" ] && continue

    matched=0
    for allowed in "$@"; do
        # Совпадением считается начало строки: «dotnet build» разрешает
        # «dotnet build --no-restore -c Release», но не «dotnet ef».
        if [ "$part" = "$allowed" ] || [ "${part#"$allowed" }" != "$part" ]; then
            matched=1
            break
        fi
    done

    if [ "$matched" -eq 0 ]; then
        deny "Команда «$part» не входит в список разрешённого на этом шаге. Разрешено: $*."
    fi
done <<< "$PARTS"

allow_silently
