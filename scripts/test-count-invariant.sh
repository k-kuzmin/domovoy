#!/usr/bin/env bash
#
# Домовой — инвариант результата: число выполненных тестовых случаев.
#
# ЗАЧЕМ
#
# У гейта целостности (scripts/guard.sh) есть перечень SUPPRESSION_PATTERNS —
# шаблоны подавления, которые ищутся в диффе PR. Перечень остаётся быстрой
# обратной связью с внятным сообщением: он называет приём по имени и
# показывает строку. Но перечисление конечно, а обходится изобретательностью:
# у теста снят Assert, набор [InlineData] опустел, тест унесён в проект,
# который не попадает под прогон. Ни один из этих приёмов не добавляет в дифф
# строку из перечня.
#
# Этот скрипт — то, что нельзя обойти незнакомым приёмом. Он не ищет
# признаков вовсе, а сравнивает результат прогона со снимком: сколько случаев
# выполнено на самом деле. Приём, о котором мы не знаем, всё равно уменьшит
# это число — либо не уменьшит и тогда не навредит.
#
# ОБХОДА НЕТ
#
# Метки, снимающей эту проверку, не существует, и это решение владельца, а не
# недоделка. Законное уменьшение числа тестов — удаление функциональности
# вместе с её тестами — перестаёт быть операцией обычного PR и становится
# ручной операцией человека: прямым коммитом в main либо временным снятием
# обязательной проверки. Искать метку agent/allow-* здесь не надо, её нет.
#
# ЧТО ПРОВЕРЯЕТСЯ
#
#   Сумма атрибута executed по всем найденным trx-отчётам равна числу из
#   снимка tests/test-count.baseline. Сравнение точное: красный и на убыль,
#   и на рост.
#
#   Красный на рост — не придирка. Устаревшая вниз база разрешала бы удалить
#   ровно столько тестов, сколько добавили после её последней правки. Цена —
#   каждый PR с новым тестом один раз краснеет и правит одну строку; число,
#   которое надо вписать, печатается в сообщении.
#
#   Снимок — файл в репозитории, а не артефакт прогона. У артефакта и кэша
#   состояние «базы нет» штатное (retention, холодный кэш, первый прогон), и
#   проверка молча зеленела бы. У файла оно означает поломку и проверяется
#   каждым прогоном, включая push в main.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ ЛОВИТ
#
#   Тест, у которого сняли Assert, а тело осталось: он выполняется, счётчик
#   не меняется. Это известная дыра, и закрывается она не числом
#   выполненных, а мутационным тестированием — отдельной задачей.
#
#   Она же не различает, какие именно случаи выполнены: перенос теста между
#   проектами при сохранении числа для неё невидим.
#
#   Приложенный к PR лишний trx-отчёт: отчёты суммируются, а *.trx и каталог
#   результатов лежат в .gitignore, который git add -f не остановит. Уменьшить
#   число настоящих случаев и добить сумму до снимка подложенным отчётом эта
#   проверка не заметит — она читает то, что нашла, и не знает, что из этого
#   пришло из прогона. Закрывается это диффовой половиной (в дифф PR не
#   попадают *.trx и файлы под каталогом результатов), которой здесь ещё нет:
#   её вносит задача #90 — там же механика обхода, два уже разобранных тупика
#   и требование воспроизвести сам обход, а не только красный харнесс.
#
#   Число случаев обязано быть детерминированным. Сегодня все данные —
#   [InlineData], тестов, пропускаемых по среде или по ОС, нет. Появление
#   [MemberData], зависящего от окружения, сделает снимок непереносимым между
#   машиной и CI — проверка при этом покраснеет, а не промолчит.
#
# РАСКЛАДКА ОТЧЁТОВ
#
# Ищутся *.trx в каталоге результатов и на один уровень вложенности вглубь.
# Наблюдённая раскладка при текущей команде из ci-fast.yml (--logger
# "trx;LogFileName=tests.trx" --results-directory TestResults) — ровно один
# файл TestResults/tests.trx; вложенный каталог с guid содержит только отчёт
# о покрытии. Второй уровень — страховка на случай смены раскладки: лучше
# найти отчёт там, где его не ждали, чем сравнить с пустотой.
#
# Отчёты суммируются, а не читается один: в день, когда появится второй
# тестовый проект, фиксированный LogFileName даст либо второй файл, либо
# затирание первого. В первом случае суммирование верно, во втором число
# упадёт и проверка покраснеет громко — молча не пройдёт ни один из двух.
#
# КАК ЗАПУСКАТЬ
#
#   bash scripts/test-count-invariant.sh
#   bash scripts/test-count-invariant.sh <каталог результатов> <файл снимка>
#
# По умолчанию каталог — TestResults, снимок — tests/test-count.baseline.
# Аргументы нужны сценариям: bash scripts/test-count-invariant.test.sh
#
# Код возврата: 0 — сходится, 1 — не сходится или сравнить не с чем.
# Кода «ошибка запуска» здесь нет намеренно: для CI разницы между «не
# сошлось» и «не смог сравнить» не существует — оба обязаны быть красными.
# Различает их текст сообщения, а не число.
#
set -uo pipefail

RESULTS_DIR="${1:-TestResults}"
BASELINE_FILE="${2:-tests/test-count.baseline}"

# ------------------------------------------------------------------
# Отчёты
# ------------------------------------------------------------------
reports=()
while IFS= read -r report; do
    [ -n "$report" ] && reports+=("$report")
done < <(find "$RESULTS_DIR" -mindepth 1 -maxdepth 2 -name '*.trx' 2>/dev/null | sort)

if [ "${#reports[@]}" -eq 0 ]; then
    printf '::error::Отчёты о тестах (*.trx) не найдены в %s и на уровень глубже. Либо тесты запускались без --logger trx, либо сменилась раскладка результатов — разобраться, а не расширять шаблон поиска.\n' \
        "$RESULTS_DIR" >&2
    exit 1
fi

EXECUTED_TOTAL=0

for report in "${reports[@]}"; do
    # Берётся первый элемент <Counters>: в trx это сводка прогона
    # (ResultSummary), остальные — вложенные, и их сложение удвоило бы число.
    counters="$(grep -o '<Counters[^>]*>' "$report" | head -n 1)"

    if [ -z "$counters" ]; then
        printf '::error::В отчёте %s нет элемента <Counters>. Формат trx сменился — молчать об этом нельзя: без счётчика инвариант сравнивает не то, что думает.\n' \
            "$report" >&2
        exit 1
    fi

    # Пробел перед именем обязателен: без него шаблон совпал бы с хвостом
    # соседнего атрибута — сегодня такого нет, потому что notExecuted пишется
    # с заглавной E, а grep регистр различает. Пробел держит гипотезу «формат
    # сменил регистр»; закреплён он сценарием харнесса «атрибут notexecuted
    # перед executed не подменяет число», который краснеет, если пробел убрать.
    executed="$(printf '%s' "$counters" \
        | grep -oE '[[:space:]]executed="[0-9]+"' \
        | head -n 1 \
        | grep -oE '[0-9]+')"

    if [ -z "$executed" ]; then
        printf '::error::В отчёте %s нет атрибута executed у <Counters>. Формат trx сменился — разобраться, а не считать по другому атрибуту.\n' \
            "$report" >&2
        exit 1
    fi

    printf '  %s: executed=%s\n' "$report" "$executed"
    EXECUTED_TOTAL=$((EXECUTED_TOTAL + executed))
done

# ------------------------------------------------------------------
# Снимок
# ------------------------------------------------------------------
if [ ! -f "$BASELINE_FILE" ]; then
    printf '::error::Снимок %s не найден — сравнить не с чем. Выполнено случаев: %s. Проверка, которая не может сравнить, обязана сказать это вслух, а не зазеленеть: заведите файл с одним числом (%s), строки с # — комментарии.\n' \
        "$BASELINE_FILE" "$EXECUTED_TOTAL" "$EXECUTED_TOTAL" >&2
    exit 1
fi

# Строки с # — комментарии, пустые игнорируются. Числом считается строка
# целиком из цифр: так правка комментария не читается как смена числа.
# tr снимает \r — снимок правят и на Windows.
BASELINE="$(tr -d '\r' < "$BASELINE_FILE" | grep -m1 -oE '^[0-9]+$')"

if [ -z "$BASELINE" ]; then
    printf '::error::В снимке %s нет строки, целиком состоящей из цифр. Выполнено случаев: %s. Впишите это число отдельной строкой — пустой или нечисловой снимок хуже отсутствующего, он выглядит рабочим.\n' \
        "$BASELINE_FILE" "$EXECUTED_TOTAL" >&2
    exit 1
fi

# ------------------------------------------------------------------
# Сравнение
# ------------------------------------------------------------------
printf 'Выполнено тестовых случаев: %s, снимок %s: %s\n' \
    "$EXECUTED_TOTAL" "$BASELINE_FILE" "$BASELINE"

if [ "$EXECUTED_TOTAL" -eq "$BASELINE" ]; then
    printf 'Инвариант числа тестов: сходится.\n'
    exit 0
fi

if [ "$EXECUTED_TOTAL" -lt "$BASELINE" ]; then
    printf '::error::Выполненных тестовых случаев стало меньше: %s против %s в снимке %s. Тест исчез из прогона — удалён, пропущен, унесён в непрогоняемый проект или лишён данных [InlineData]. Метки, снимающей эту проверку, нет: если уменьшение законно (удалена функциональность вместе с тестами), снимок правит человек вручную, а не PR агента.\n' \
        "$EXECUTED_TOTAL" "$BASELINE" "$BASELINE_FILE" >&2
    exit 1
fi

printf '::error::Выполненных тестовых случаев стало больше: %s против %s в снимке %s. Это нормальная работа, но снимок обязан совпадать: впишите %s в %s — устаревшая вниз база разрешала бы удалить ровно столько тестов, сколько добавили после её последней правки.\n' \
    "$EXECUTED_TOTAL" "$BASELINE" "$BASELINE_FILE" "$EXECUTED_TOTAL" "$BASELINE_FILE" >&2
exit 1
